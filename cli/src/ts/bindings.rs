//! WIT -> TypeScript for scriptc, written to the app's `bindings/`:
//!
//!   <interface>.ts  per interface: its records, and its functions as typed
//!                   TypeScript (`page.setHtml(name, html)`), or for an
//!                   export, the interface the app implements (`Handler`)
//!   raw.ts          the scriptc callbacks those functions call, one per
//!                   WIT import, in core-ABI shape (strings as strings,
//!                   results through a byte buffer)
//!   abi.ts          reading canonical-ABI values out of linear memory
//!   entry.ts        the module scriptc compiles: one function per WIT
//!                   export, which reads the arguments and calls the app
//!   profile.json    scriptc's description of callbacks and exports
//!   node.mjs        for unit tests under Node (`node --import
//!                   ./bindings/node.mjs --test`): there the callbacks
//!                   fail when called, so tests pass fakes instead
//!
//! Supported: bool, integers, f64, string, list, option, tuple, record,
//! enum (a union of strings: `"starter" | "team"`) and result (`Result`,
//! `{ ok: true, value }` or `{ ok: false, error }`). 64-bit integers are
//! numbers, exact up to 2^53, and only come back from the shell: no
//! parameter takes one. Anything else in the WIT is an error naming the
//! type.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use anyhow::{Result, bail};
use serde_json::json;
use wit_parser::abi::WasmType;
use wit_parser::{Docs, Int, InterfaceId, Resolve, SizeAlign, Type, TypeDefKind, TypeOwner, WorldId};

use super::{WitFn, exports, imports};

/// The callback that copies bytes out of linear memory; adapt.rs implements it.
pub(crate) const MEM_READ: &str = "appos_abi_mem_read";
/// scriptc's ABI prefix; its module init function is `app_init`.
pub(crate) const PREFIX: &str = "app";

const HEADER: &str = "// Generated by `appos build` from wit/. Don't edit: every build rewrites it.\n";

/// Node runs the app's TypeScript as it is (type stripping), but raw.ts only
/// declares the callbacks: AppOS provides them. This hook gives Node a raw.ts
/// where each one throws, so code that imports the bindings loads in tests.
const NODE: &str = r#"
import { readFileSync } from "node:fs";
import { registerHooks } from "node:module";

registerHooks({
  load(url, context, next) {
    if (!url.endsWith("/bindings/raw.ts")) return next(url, context);
    const names = [...readFileSync(new URL(url), "utf8").matchAll(/^export declare function (\w+)/gm)].map((m) => m[1]);
    const source = names
      .map((name) => `export function ${name}() { throw new Error("${name} runs only in AppOS: pass a fake in tests"); }`)
      .join("\n");
    return { format: "module", source, shortCircuit: true };
  },
});
"#;

const ABI: &str = r#"
// Canonical-ABI values in linear memory, where the shell puts arguments and
// results. They are copied into TypeScript values with one callback.
import { appos_abi_mem_read } from "./raw.ts";

const decoder = new TextDecoder();

export function view(b: Uint8Array): DataView {
  return new DataView(b.buffer, b.byteOffset, b.byteLength);
}

/** A copy of `len` bytes at `ptr`. */
export function bytesAt(ptr: number, len: number): Uint8Array {
  const b = new Uint8Array(len);
  if (len > 0) appos_abi_mem_read(ptr, b);
  return b;
}

export function stringAt(ptr: number, len: number): string {
  return decoder.decode(bytesAt(ptr, len));
}

export function listAt<T>(ptr: number, len: number, size: number, read: (v: DataView, o: number) => T): T[] {
  const out: T[] = [];
  if (len === 0) return out;
  const v = view(bytesAt(ptr, len * size));
  for (let i = 0; i < len; i++) out.push(read(v, i * size));
  return out;
}

export function readString(v: DataView, o: number): string {
  return stringAt(v.getUint32(o, true), v.getUint32(o + 4, true));
}

export function readBytes(v: DataView, o: number): Uint8Array {
  return bytesAt(v.getUint32(o, true), v.getUint32(o + 4, true));
}

export function readList<T>(v: DataView, o: number, size: number, read: (v: DataView, o: number) => T): T[] {
  return listAt<T>(v.getUint32(o, true), v.getUint32(o + 4, true), size, read);
}

/** A WIT result: what a function answers, or why it couldn't. */
export type Result<T, E> = { ok: true; value: T } | { ok: false; error: E };

export function resultOk<T, E>(value: T): Result<T, E> {
  return { ok: true, value };
}

export function resultErr<T, E>(error: E): Result<T, E> {
  return { ok: false, error };
}
"#;

/// The files for `bindings/`, by name.
pub fn generate(resolve: &Resolve, world: WorldId) -> Result<Vec<(String, String)>> {
    let mut sizes = SizeAlign::default();
    sizes.fill(resolve)?;
    let g = Gen { resolve, sizes, files: file_names(resolve, world) };
    let imports = imports(resolve, world);
    let exports = exports(resolve, world);

    let mut files: BTreeMap<InterfaceId, File> = g.files.iter().map(|(id, name)| (*id, File::new(name))).collect();
    // Records and enums first, in the interface that defines them.
    for (&id, file) in &mut files {
        for (name, &ty) in &resolve.interfaces[id].types {
            let def = &resolve.types[ty];
            if let TypeDefKind::Enum(e) = &def.kind {
                let ts = pascal(name);
                let cases: Vec<String> = e.cases.iter().map(|c| format!("\"{}\"", c.name)).collect();
                file.body.push_str(&doc(&def.docs, ""));
                writeln!(file.body, "export type {ts} = {};\n", cases.join(" | "))?;
                writeln!(file.body, "const {}Cases: {ts}[] = [{}];\n", camel(name), cases.join(", "))?;
                writeln!(file.body, "export function lift{ts}(n: number): {ts} {{\n  return {}Cases[n];\n}}\n", camel(name))?;
                writeln!(file.body, "export function lower{ts}(x: {ts}): number {{\n  return {}Cases.indexOf(x);\n}}\n", camel(name))?;
            }
            if let TypeDefKind::Record(r) = &def.kind {
                let ts = pascal(name);
                file.body.push_str(&doc(&def.docs, ""));
                writeln!(file.body, "export interface {ts} {{")?;
                for field in &r.fields {
                    file.body.push_str(&doc(&field.docs, "  "));
                    let ts_field = g.ts_type(&field.ty, file)?;
                    writeln!(file.body, "  {}: {ts_field};", camel(&field.name))?;
                }
                file.body.push_str("}\n\n");
                writeln!(file.body, "export function lift{ts}(v: DataView, o: number): {ts} {{\n  return {{")?;
                let offsets = g.sizes.field_offsets(r.fields.iter().map(|f| &f.ty));
                for (field, (offset, _)) in r.fields.iter().zip(offsets) {
                    let value = g.lift(&field.ty, "v", &Off::at("o", offset.size_wasm32()), file, 0)?;
                    writeln!(file.body, "    {}: {value},", camel(&field.name))?;
                }
                file.body.push_str("  };\n}\n\n");
            }
        }
    }

    let mut callbacks = vec![json!({ "name": MEM_READ, "params": ["u32", "bytes"], "returns": "void" })];
    let mut raw = format!(
        "{HEADER}\n// The callbacks behind the typed functions; appos build connects each to its WIT import.\nexport declare function {MEM_READ}(src: number, dst: Uint8Array): void;\n"
    );
    for w in &imports {
        let Some(id) = w.interface else { bail!("world-level function {} isn't supported for TypeScript apps yet", w.func.name) };
        let file = files.get_mut(&id).expect("every interface has a file");
        let cb = g.import_fn(w, file)?;
        let params: Vec<String> = cb.args.iter().enumerate().map(|(i, a)| format!("a{i}: {}", a.ts)).collect();
        writeln!(raw, "export declare function {}({}): {};", w.c_name, params.join(", "), cb.ret_ts)?;
        callbacks.push(json!({ "name": w.c_name, "params": cb.args.iter().map(|a| a.kind).collect::<Vec<_>>(), "returns": cb.ret_kind }));
    }

    let mut entry = File::new("entry");
    let mut profile_exports = Vec::new();
    let mut implemented = BTreeSet::new();
    for w in &exports {
        let Some(id) = w.interface else { bail!("world-level export {} isn't supported for TypeScript apps yet", w.func.name) };
        let iface = resolve.interfaces[id].name.clone().unwrap_or_default();
        if implemented.insert(id) {
            let file = files.get_mut(&id).expect("every interface has a file");
            g.export_interface(id, file)?;
        }
        entry.uses.entry("../src/lib.ts".into()).or_default().insert(camel(&iface));
        let (params, kinds, body, ret_kind) = g.export_fn(w, &format!("{}.{}", camel(&iface), ident(&camel(&w.func.name))), &mut entry)?;
        let ret_ts = if ret_kind == "void" { "void" } else { "number" };
        writeln!(entry.body, "export function {}({params}): {ret_ts} {{\n{body}}}\n", w.c_name)?;
        profile_exports.push(json!({ "export": w.c_name, "symbol": w.c_name, "params": kinds, "returns": ret_kind }));
    }

    let profile = json!({
        "profile_format": 1,
        "name": PREFIX,
        "entry": "entry.ts",
        "emission": "llvm",
        "abi": {
            "prefix": PREFIX,
            "init_symbol": format!("{PREFIX}_init"),
            "sink_register_symbol": format!("{PREFIX}_sink"),
            "callback_register_symbol": format!("{PREFIX}_cb"),
        },
        "callbacks": callbacks,
        "exports": profile_exports,
    });

    let mut out = vec![
        ("abi.ts".to_string(), format!("{HEADER}{ABI}")),
        ("raw.ts".to_string(), raw),
        ("entry.ts".to_string(), entry.finish()),
        ("profile.json".to_string(), serde_json::to_string_pretty(&profile)? + "\n"),
        ("node.mjs".to_string(), format!("{HEADER}{NODE}")),
    ];
    out.extend(files.into_values().map(|f| (format!("{}.ts", f.name), f.finish())));
    Ok(out)
}

/// One file per interface, by its name; qualified by package when two
/// share a name or a name is taken by a fixed file.
fn file_names(resolve: &Resolve, world: WorldId) -> BTreeMap<InterfaceId, String> {
    let w = &resolve.worlds[world];
    let ids: Vec<InterfaceId> = w
        .imports
        .values()
        .chain(w.exports.values())
        .filter_map(|item| match item {
            wit_parser::WorldItem::Interface { id, .. } => Some(*id),
            _ => None,
        })
        .collect();
    let short = |id: &InterfaceId| resolve.interfaces[*id].name.clone().unwrap_or_else(|| "interface".into());
    ids.iter()
        .map(|id| {
            let name = short(id);
            let taken = ["abi", "raw", "entry", "profile"].contains(&name.as_str()) || ids.iter().filter(|o| short(o) == name).count() > 1;
            let file = match resolve.interfaces[*id].package {
                Some(p) if taken => format!("{}-{}-{name}", resolve.packages[p].name.namespace, resolve.packages[p].name.name),
                _ => name,
            };
            (*id, file)
        })
        .collect()
}

struct Gen<'a> {
    resolve: &'a Resolve,
    sizes: SizeAlign,
    files: BTreeMap<InterfaceId, String>,
}

/// A generated file: its imports, collected while writing the body.
struct File {
    name: String,
    uses: BTreeMap<String, BTreeSet<String>>,
    type_uses: BTreeMap<String, BTreeSet<String>>,
    body: String,
    temps: usize,
}

impl File {
    fn new(name: &str) -> File {
        File { name: name.into(), uses: BTreeMap::new(), type_uses: BTreeMap::new(), body: String::new(), temps: 0 }
    }

    fn uses(&mut self, module: &str, name: &str) {
        if module != format!("./{}.ts", self.name) {
            self.uses.entry(module.into()).or_default().insert(name.into());
        }
    }

    fn uses_type(&mut self, module: &str, name: &str) {
        if module != format!("./{}.ts", self.name) {
            self.type_uses.entry(module.into()).or_default().insert(name.into());
        }
    }

    fn temp(&mut self) -> String {
        self.temps += 1;
        format!("t{}", self.temps)
    }

    fn finish(self) -> String {
        let mut out = HEADER.to_string();
        for (module, names) in &self.type_uses {
            out += &format!("import type {{ {} }} from \"{module}\";\n", names.iter().cloned().collect::<Vec<_>>().join(", "));
        }
        for (module, names) in &self.uses {
            out += &format!("import {{ {} }} from \"{module}\";\n", names.iter().cloned().collect::<Vec<_>>().join(", "));
        }
        out + "\n" + self.body.trim_end() + "\n"
    }
}

/// An offset into a DataView: `o + 8`.
struct Off {
    var: String,
    n: usize,
}

impl Off {
    fn at(var: &str, n: usize) -> Off {
        Off { var: var.into(), n }
    }

    fn plus(&self, n: usize) -> Off {
        Off { var: self.var.clone(), n: self.n + n }
    }
}

impl std::fmt::Display for Off {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match (self.var.as_str(), self.n) {
            ("", n) => write!(f, "{n}"),
            (v, 0) => write!(f, "{v}"),
            (v, n) => write!(f, "{v} + {n}"),
        }
    }
}

/// One core argument of a callback: the TypeScript expression and how
/// scriptc passes it.
struct Arg {
    expr: String,
    kind: &'static str,
    ts: &'static str,
}

struct Callback {
    args: Vec<Arg>,
    ret_kind: &'static str,
    ret_ts: &'static str,
}

fn unsupported(what: &str) -> anyhow::Error {
    anyhow::anyhow!("{what} in the WIT isn't supported for TypeScript apps yet")
}

impl Gen<'_> {
    fn module_of(&self, owner: TypeOwner, what: &str) -> Result<String> {
        match owner {
            TypeOwner::Interface(id) if self.files.contains_key(&id) => Ok(format!("./{}.ts", self.files[&id])),
            _ => Err(unsupported(what)),
        }
    }

    fn ts_type(&self, ty: &Type, f: &mut File) -> Result<String> {
        Ok(match ty {
            Type::Bool => "boolean".into(),
            Type::U8 | Type::U16 | Type::U32 | Type::S8 | Type::S16 | Type::S32 | Type::F64 => "number".into(),
            Type::String => "string".into(),
            Type::U64 | Type::S64 => "number".into(),
            Type::F32 => return Err(unsupported("f32")),
            Type::Char => return Err(unsupported("char")),
            Type::ErrorContext => return Err(unsupported("error-context")),
            Type::Id(id) => {
                let def = &self.resolve.types[*id];
                match &def.kind {
                    TypeDefKind::Type(t) => self.ts_type(t, f)?,
                    TypeDefKind::Record(_) => {
                        let name = pascal(def.name.as_deref().unwrap_or("record"));
                        f.uses_type(&self.module_of(def.owner, "an anonymous record")?, &name);
                        name
                    }
                    TypeDefKind::List(Type::U8) => "Uint8Array".into(),
                    TypeDefKind::List(t) => {
                        let inner = self.ts_type(t, f)?;
                        if inner.contains(' ') && !inner.starts_with('[') { format!("({inner})[]") } else { format!("{inner}[]") }
                    }
                    TypeDefKind::Option(t) => format!("{} | undefined", self.ts_type(t, f)?),
                    TypeDefKind::Tuple(t) => {
                        let parts = t.types.iter().map(|t| self.ts_type(t, f)).collect::<Result<Vec<_>>>()?;
                        format!("[{}]", parts.join(", "))
                    }
                    TypeDefKind::Enum(_) => {
                        let name = pascal(def.name.as_deref().unwrap_or("enum"));
                        f.uses_type(&self.module_of(def.owner, "an anonymous enum")?, &name);
                        name
                    }
                    TypeDefKind::Result(r) => {
                        f.uses_type("./abi.ts", "Result");
                        format!("Result<{}, {}>", self.ts_or_undefined(r.ok.as_ref(), f)?, self.ts_or_undefined(r.err.as_ref(), f)?)
                    }
                    other => return Err(unsupported(kind_name(other))),
                }
            }
        })
    }

    /// The TypeScript type of a result's side; `undefined` for none.
    fn ts_or_undefined(&self, ty: Option<&Type>, f: &mut File) -> Result<String> {
        ty.map_or_else(|| Ok("undefined".into()), |t| self.ts_type(t, f))
    }

    /// A value read from linear memory, as a TypeScript expression.
    fn lift(&self, ty: &Type, v: &str, o: &Off, f: &mut File, depth: usize) -> Result<String> {
        Ok(match ty {
            Type::Bool => format!("({v}.getUint8({o}) !== 0)"),
            Type::U8 => format!("{v}.getUint8({o})"),
            Type::S8 => format!("{v}.getInt8({o})"),
            Type::U16 => format!("{v}.getUint16({o}, true)"),
            Type::S16 => format!("{v}.getInt16({o}, true)"),
            Type::U32 => format!("{v}.getUint32({o}, true)"),
            Type::S32 => format!("{v}.getInt32({o}, true)"),
            Type::F64 => format!("{v}.getFloat64({o}, true)"),
            // Two halves: a number holds 2^53 exactly.
            Type::U64 => format!("({v}.getUint32({o}, true) + {v}.getUint32({}, true) * 4294967296)", o.plus(4)),
            Type::S64 => format!("({v}.getUint32({o}, true) + {v}.getInt32({}, true) * 4294967296)", o.plus(4)),
            Type::String => {
                f.uses("./abi.ts", "readString");
                format!("readString({v}, {o})")
            }
            Type::Id(id) => {
                let def = &self.resolve.types[*id];
                match &def.kind {
                    TypeDefKind::Type(t) => self.lift(t, v, o, f, depth)?,
                    TypeDefKind::Enum(e) => {
                        let lift = format!("lift{}", pascal(def.name.as_deref().unwrap_or("enum")));
                        f.uses(&self.module_of(def.owner, "an anonymous enum")?, &lift);
                        let tag = match e.tag() {
                            Int::U8 => format!("{v}.getUint8({o})"),
                            Int::U16 => format!("{v}.getUint16({o}, true)"),
                            _ => format!("{v}.getUint32({o}, true)"),
                        };
                        format!("{lift}({tag})")
                    }
                    TypeDefKind::Result(r) => {
                        let ts = format!("{}, {}", self.ts_or_undefined(r.ok.as_ref(), f)?, self.ts_or_undefined(r.err.as_ref(), f)?);
                        let payload = o.plus(self.sizes.payload_offset(Int::U8, [r.ok.as_ref(), r.err.as_ref()]).size_wasm32());
                        let ok = r.ok.as_ref().map_or_else(|| Ok("undefined".to_string()), |t| self.lift(t, v, &payload, f, depth))?;
                        let err = r.err.as_ref().map_or_else(|| Ok("undefined".to_string()), |t| self.lift(t, v, &payload, f, depth))?;
                        f.uses("./abi.ts", "resultOk");
                        f.uses("./abi.ts", "resultErr");
                        format!("({v}.getUint8({o}) === 0 ? resultOk<{ts}>({ok}) : resultErr<{ts}>({err}))")
                    }
                    TypeDefKind::Record(_) => {
                        let lift = format!("lift{}", pascal(def.name.as_deref().unwrap_or("record")));
                        f.uses(&self.module_of(def.owner, "an anonymous record")?, &lift);
                        format!("{lift}({v}, {o})")
                    }
                    TypeDefKind::List(Type::U8) => {
                        f.uses("./abi.ts", "readBytes");
                        format!("readBytes({v}, {o})")
                    }
                    TypeDefKind::List(t) => {
                        f.uses("./abi.ts", "readList");
                        let (lv, lo) = (format!("v{}", depth + 1), format!("o{}", depth + 1));
                        let ts = self.ts_type(t, f)?;
                        let item = self.lift(t, &lv, &Off::at(&lo, 0), f, depth + 1)?;
                        format!("readList<{ts}>({v}, {o}, {}, ({lv}: DataView, {lo}: number): {ts} => {item})", self.sizes.size(t).size_wasm32())
                    }
                    TypeDefKind::Option(t) => {
                        let payload = self.sizes.payload_offset(Int::U8, [None, Some(t)]).size_wasm32();
                        format!("({v}.getUint8({o}) === 0 ? undefined : {})", self.lift(t, v, &o.plus(payload), f, depth)?)
                    }
                    TypeDefKind::Tuple(t) => {
                        let ts = self.ts_type(ty, f)?;
                        let mut parts = Vec::new();
                        for (offset, t) in self.sizes.field_offsets(&t.types) {
                            parts.push(self.lift(t, v, &o.plus(offset.size_wasm32()), f, depth)?);
                        }
                        format!("[{}] as {ts}", parts.join(", "))
                    }
                    other => return Err(unsupported(kind_name(other))),
                }
            }
            other => return Err(unsupported(&format!("{other:?}"))),
        })
    }

    /// A value passed as core parameters (an export's arguments), consuming
    /// their names in order.
    fn flat_lift(&self, ty: &Type, p: &mut std::vec::IntoIter<String>, f: &mut File) -> Result<String> {
        let mut next = || p.next().ok_or_else(|| anyhow::anyhow!("fewer core parameters than the WIT type needs"));
        Ok(match ty {
            Type::Bool => format!("({} !== 0)", next()?),
            Type::U8 | Type::U16 | Type::U32 | Type::F64 => next()?,
            Type::S8 | Type::S16 | Type::S32 => format!("({} | 0)", next()?),
            Type::String => {
                f.uses("./abi.ts", "stringAt");
                format!("stringAt({}, {})", next()?, next()?)
            }
            Type::Id(id) => {
                let def = &self.resolve.types[*id];
                match &def.kind {
                    TypeDefKind::Type(t) => self.flat_lift(t, p, f)?,
                    TypeDefKind::Record(r) => {
                        self.ts_type(ty, f)?;
                        let mut fields = Vec::new();
                        for field in &r.fields {
                            fields.push(format!("{}: {}", camel(&field.name), self.flat_lift(&field.ty, p, f)?));
                        }
                        format!("{{ {} }}", fields.join(", "))
                    }
                    TypeDefKind::List(Type::U8) => {
                        f.uses("./abi.ts", "bytesAt");
                        format!("bytesAt({}, {})", next()?, next()?)
                    }
                    TypeDefKind::List(t) => {
                        f.uses("./abi.ts", "listAt");
                        let (ptr, len) = (next()?, next()?);
                        let ts = self.ts_type(t, f)?;
                        let item = self.lift(t, "v1", &Off::at("o1", 0), f, 1)?;
                        format!("listAt<{ts}>({ptr}, {len}, {}, (v1: DataView, o1: number): {ts} => {item})", self.sizes.size(t).size_wasm32())
                    }
                    TypeDefKind::Option(t) => {
                        let tag = next()?;
                        format!("({tag} === 0 ? undefined : {})", self.flat_lift(t, p, f)?)
                    }
                    TypeDefKind::Enum(_) => {
                        let lift = format!("lift{}", pascal(def.name.as_deref().unwrap_or("enum")));
                        f.uses(&self.module_of(def.owner, "an anonymous enum")?, &lift);
                        format!("{lift}({})", next()?)
                    }
                    TypeDefKind::Tuple(t) => {
                        let ts = self.ts_type(ty, f)?;
                        let parts = t.types.iter().map(|t| self.flat_lift(t, p, f)).collect::<Result<Vec<_>>>()?;
                        format!("[{}] as {ts}", parts.join(", "))
                    }
                    other => return Err(unsupported(kind_name(other))),
                }
            }
            other => return Err(unsupported(&format!("{other:?}"))),
        })
    }

    /// A value passed to a callback: its core arguments, with statements
    /// for temporaries in `pre`.
    fn lower(&self, ty: &Type, expr: &str, pre: &mut Vec<String>, args: &mut Vec<Arg>, f: &mut File) -> Result<()> {
        let arg = |kind, ts| Arg { expr: expr.to_string(), kind, ts };
        match ty {
            Type::Bool => args.push(arg("bool", "boolean")),
            Type::U8 | Type::U16 | Type::U32 => args.push(arg("u32", "number")),
            Type::S8 | Type::S16 | Type::S32 => args.push(arg("i32", "number")),
            Type::F64 => args.push(arg("f64", "number")),
            Type::String => args.push(arg("string", "string")),
            Type::U64 | Type::S64 => return Err(unsupported("a 64-bit integer as a parameter")),
            Type::Id(id) => match &self.resolve.types[*id].kind {
                TypeDefKind::Type(t) => self.lower(t, expr, pre, args, f)?,
                TypeDefKind::Enum(_) => {
                    let def = &self.resolve.types[*id];
                    let lower = format!("lower{}", pascal(def.name.as_deref().unwrap_or("enum")));
                    f.uses(&self.module_of(def.owner, "an anonymous enum")?, &lower);
                    args.push(Arg { expr: format!("{lower}({expr})"), kind: "u32", ts: "number" });
                }
                TypeDefKind::List(Type::U8) => args.push(arg("bytes", "Uint8Array")),
                TypeDefKind::Option(t) => {
                    let zero = match self.deref(t) {
                        Type::Bool => "false".to_string(),
                        Type::String => "\"\"".to_string(),
                        Type::Id(id) => match &self.resolve.types[id].kind {
                            TypeDefKind::List(Type::U8) => "new Uint8Array(0)".to_string(),
                            // Any case: the shell ignores it without the option.
                            TypeDefKind::Enum(e) => format!("\"{}\"", e.cases[0].name),
                            _ => return Err(unsupported("an option of a compound type as a parameter")),
                        },
                        _ => "0".to_string(),
                    };
                    let t0 = f.temp();
                    pre.push(format!("const {t0} = {expr};"));
                    args.push(Arg { expr: format!("{t0} === undefined ? 0 : 1"), kind: "u32", ts: "number" });
                    self.lower(t, &format!("({t0} ?? {zero})"), pre, args, f)?;
                }
                TypeDefKind::Record(r) => {
                    let t0 = f.temp();
                    pre.push(format!("const {t0} = {expr};"));
                    for field in &r.fields {
                        self.lower(&field.ty, &format!("{t0}.{}", camel(&field.name)), pre, args, f)?;
                    }
                }
                TypeDefKind::Tuple(t) => {
                    let t0 = f.temp();
                    pre.push(format!("const {t0} = {expr};"));
                    for (i, t) in t.types.iter().enumerate() {
                        self.lower(t, &format!("{t0}[{i}]"), pre, args, f)?;
                    }
                }
                TypeDefKind::List(_) => return Err(unsupported("a list parameter (other than list<u8>)")),
                other => return Err(unsupported(kind_name(other))),
            },
            other => return Err(unsupported(&format!("{other:?}"))),
        }
        Ok(())
    }

    fn deref(&self, ty: &Type) -> Type {
        match ty {
            Type::Id(id) => match &self.resolve.types[*id].kind {
                TypeDefKind::Type(t) => self.deref(t),
                _ => *ty,
            },
            _ => *ty,
        }
    }

    /// An imported function as typed TypeScript; returns its callback.
    fn import_fn(&self, w: &WitFn, f: &mut File) -> Result<Callback> {
        let func = w.func;
        if w.sig.indirect_params {
            bail!("{} has too many parameters for TypeScript apps yet (16 core values at most)", func.name);
        }
        let mut params = Vec::new();
        let (mut pre, mut args) = (Vec::new(), Vec::new());
        for p in &func.params {
            let name = ident(&camel(&p.name));
            params.push(format!("{name}: {}", self.ts_type(&p.ty, f)?));
            self.lower(&p.ty, &name, &mut pre, &mut args, f)?;
        }
        let ret_ts = match &func.result {
            Some(t) => self.ts_type(t, f)?,
            None => "void".into(),
        };
        f.uses("./raw.ts", &w.c_name);
        let mut body = String::new();
        for line in &pre {
            writeln!(body, "  {line}")?;
        }
        let (ret_kind, ret_raw) = match &func.result {
            Some(t) if w.sig.retptr => {
                f.uses("./abi.ts", "view");
                writeln!(body, "  const ret$ = new Uint8Array({});", self.sizes.size(t).size_wasm32())?;
                args.push(Arg { expr: "ret$".into(), kind: "bytes", ts: "Uint8Array" });
                writeln!(body, "  {}({});", w.c_name, exprs(&args))?;
                writeln!(body, "  const v = view(ret$);\n  return {};", self.lift(t, "v", &Off::at("", 0), f, 0)?)?;
                ("void", "void")
            }
            Some(t) => {
                let call = format!("{}({})", w.c_name, exprs(&args));
                let (kind, value) = match self.deref(t) {
                    Type::Bool => ("u32", format!("{call} !== 0")),
                    Type::U8 | Type::U16 | Type::U32 => ("u32", call),
                    Type::S8 | Type::S16 | Type::S32 => ("i32", call),
                    Type::F64 => ("f64", call),
                    _ => return Err(unsupported(&format!("the result of {}", func.name))),
                };
                writeln!(body, "  return {value};")?;
                (kind, "number")
            }
            None => {
                writeln!(body, "  {}({});", w.c_name, exprs(&args))?;
                ("void", "void")
            }
        };
        f.body.push_str(&doc(&func.docs, ""));
        writeln!(f.body, "export function {}({}): {ret_ts} {{\n{body}}}\n", ident(&camel(&func.name)), params.join(", "))?;
        Ok(Callback { args, ret_kind, ret_ts: ret_raw })
    }

    /// The interface the app implements for an exported WIT interface.
    fn export_interface(&self, id: InterfaceId, f: &mut File) -> Result<()> {
        let iface = &self.resolve.interfaces[id];
        let name = pascal(iface.name.as_deref().unwrap_or("exports"));
        f.body.push_str(&doc(&iface.docs, ""));
        writeln!(f.body, "export interface {name} {{")?;
        for func in iface.functions.values() {
            let params = func.params.iter().map(|p| Ok(format!("{}: {}", ident(&camel(&p.name)), self.ts_type(&p.ty, f)?))).collect::<Result<Vec<_>>>()?;
            let ret = match &func.result {
                Some(t) => self.ts_type(t, f)?,
                None => "void".into(),
            };
            f.body.push_str(&doc(&func.docs, "  "));
            writeln!(f.body, "  {}({}): {ret};", ident(&camel(&func.name)), params.join(", "))?;
        }
        f.body.push_str("}\n\n");
        Ok(())
    }

    /// An export in entry.ts: (parameters, scriptc kinds, body, result kind).
    fn export_fn(&self, w: &WitFn, call: &str, f: &mut File) -> Result<(String, Vec<&'static str>, String, &'static str)> {
        let func = w.func;
        let mut kinds = Vec::new();
        for t in &w.sig.params {
            kinds.push(match t {
                WasmType::I32 | WasmType::Pointer | WasmType::Length => "u32",
                WasmType::F64 => "f64",
                _ => return Err(unsupported(&format!("a {t:?} parameter in {}", func.name))),
            });
        }
        let names: Vec<String> = (0..kinds.len()).map(|i| format!("p{i}")).collect();
        let params = names.iter().zip(&kinds).map(|(n, _)| format!("{n}: number")).collect::<Vec<_>>().join(", ");
        let mut body = String::new();
        let mut values = Vec::new();
        if w.sig.indirect_params {
            f.uses("./abi.ts", "view");
            f.uses("./abi.ts", "bytesAt");
            let types: Vec<&Type> = func.params.iter().map(|p| &p.ty).collect();
            let size = self.sizes.record(types.iter().copied()).size.size_wasm32();
            writeln!(body, "  const v = view(bytesAt(p0, {size}));")?;
            for (offset, t) in self.sizes.field_offsets(types) {
                values.push(self.lift(t, "v", &Off::at("", offset.size_wasm32()), f, 0)?);
            }
        } else {
            let mut it = names.into_iter();
            for p in &func.params {
                values.push(self.flat_lift(&p.ty, &mut it, f)?);
            }
        }
        let call = format!("{call}({})", values.join(", "));
        let ret_kind = match func.result.as_ref().map(|t| self.deref(t)) {
            None => {
                writeln!(body, "  {call};")?;
                "void"
            }
            Some(Type::Bool) => {
                writeln!(body, "  return {call} ? 1 : 0;")?;
                "u32"
            }
            Some(Type::U8 | Type::U16 | Type::U32) => {
                writeln!(body, "  return {call};")?;
                "u32"
            }
            Some(Type::S8 | Type::S16 | Type::S32) => {
                writeln!(body, "  return {call};")?;
                "i32"
            }
            Some(Type::F64) => {
                writeln!(body, "  return {call};")?;
                "f64"
            }
            Some(_) => return Err(unsupported(&format!("the result of the export {}", func.name))),
        };
        Ok((params, kinds, body, ret_kind))
    }
}

fn exprs(args: &[Arg]) -> String {
    args.iter().map(|a| a.expr.as_str()).collect::<Vec<_>>().join(", ")
}

fn kind_name(kind: &TypeDefKind) -> &'static str {
    match kind {
        TypeDefKind::Resource | TypeDefKind::Handle(_) => "a resource",
        TypeDefKind::Flags(_) => "flags",
        TypeDefKind::Variant(_) => "a variant",
        TypeDefKind::Enum(_) => "an enum",
        TypeDefKind::Result(_) => "a result",
        TypeDefKind::Map(..) => "a map",
        TypeDefKind::FixedLengthList(..) => "a fixed-length list",
        TypeDefKind::Future(_) | TypeDefKind::Stream(_) => "async",
        _ => "this type",
    }
}

/// WIT docs as a TSDoc comment.
fn doc(docs: &Docs, indent: &str) -> String {
    let Some(text) = docs.contents.as_deref().map(str::trim).filter(|t| !t.is_empty()) else { return String::new() };
    let lines: Vec<&str> = text.lines().collect();
    if lines.len() == 1 {
        return format!("{indent}/** {} */\n", lines[0]);
    }
    let mut out = format!("{indent}/**\n");
    for line in lines {
        out += &format!("{indent} * {line}\n").replace(" * \n", " *\n");
    }
    out + format!("{indent} */\n").as_str()
}

/// `set-html` -> `setHtml`.
fn camel(name: &str) -> String {
    let mut out = String::new();
    for (i, part) in name.split('-').enumerate() {
        if i == 0 {
            out.push_str(part);
        } else {
            out.push_str(&pascal(part));
        }
    }
    out
}

/// `request` -> `Request`, `wall-clock` -> `WallClock`.
fn pascal(name: &str) -> String {
    name.split('-')
        .map(|w| {
            let mut c = w.chars();
            c.next().map(|f| f.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default()
        })
        .collect()
}

/// A JavaScript identifier: reserved words get a trailing underscore
/// (`kv.delete` is `kv.delete_`).
fn ident(name: &str) -> String {
    const RESERVED: &[&str] = &[
        "await",
        "break",
        "case",
        "catch",
        "class",
        "const",
        "continue",
        "debugger",
        "default",
        "delete",
        "do",
        "else",
        "enum",
        "export",
        "extends",
        "false",
        "finally",
        "for",
        "function",
        "if",
        "implements",
        "import",
        "in",
        "instanceof",
        "interface",
        "let",
        "new",
        "null",
        "package",
        "private",
        "protected",
        "public",
        "return",
        "static",
        "super",
        "switch",
        "this",
        "throw",
        "true",
        "try",
        "typeof",
        "var",
        "void",
        "while",
        "with",
        "yield",
        "v",
    ];
    if RESERVED.contains(&name) { format!("{name}_") } else { name.to_string() }
}

