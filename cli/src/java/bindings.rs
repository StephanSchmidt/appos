/// A Java identifier: a keyword gets a trailing `_`.
fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) { format!("{name}_") } else { name.to_string() }
}

/// A record component: also not one of Object's methods.
fn field_ident(name: &str) -> String {
    let name = camel(name);
    match name.as_str() {
        "hashCode" | "toString" | "equals" | "getClass" | "notify" | "notifyAll" | "wait" | "clone" | "finalize" => format!("{name}_"),
        _ => ident(&name),
    }
}

