//! WIT -> Java, written to the app's `bindings/appos/wit/Wit.java`, the
//! class `appos.wit.Wit`:
//!
//!   - per imported interface a class of static methods that take and
//!     return Java values (`Wit.Page.setHtml(name, html)`, `Wit.Kv.get(key)`
//!     returns `Optional<String>`), with the interface's records
//!   - per exported interface a Java interface (`Wit.Handler`) that the
//!     app's class `app.App` implements; the world's exports call it
//!   - `cabi_realloc` and the canonical ABI over TeaVM's linear memory
//!     (`org.teavm.interop.Address`), with strings in UTF-16 like Java's
//!
//! Java objects live on the WebAssembly GC heap, so what crosses to the
//! shell is copied: the shell's arguments are read into Java objects, and a
//! call's arguments are written to linear memory first.
//!
//! Types: bool boolean; u8 to u32, s8 to s32 and char (a code point) int;
//! u64 and s64 long; f32 float; f64 double; string String; list<T> List;
//! option<T> Optional; tuple<..> Wit.Tuple2 and up; record a Java record.
//! Anything else in the WIT is an error naming the type.

use std::collections::{BTreeMap, BTreeSet, HashSet};
use std::fmt::Write as _;

use anyhow::{Result, bail};
use wit_parser::abi::WasmType;
use wit_parser::{Docs, InterfaceId, Resolve, SizeAlign, Type, TypeDefKind, TypeId, TypeOwner, WorldId};

use crate::ts::{WitFn, exports, imports};

/// The generated file, below `bindings/`.
pub const FILE: &str = "appos/wit/Wit.java";
/// The app's class, which implements the world's exports.
const APP: &str = "app.App";

const HEADER: &str = "// Generated by `appos build` from wit/. Don't edit: every build rewrites it.\n";

const IMPORTS: &str = "package appos.wit;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.function.IntFunction;
import java.util.function.ObjIntConsumer;
import org.teavm.interop.Address;
import org.teavm.interop.Export;
import org.teavm.interop.Import;
import org.teavm.runtime.heap.Heap;
";

/// cabi_realloc and the canonical ABI.
const ABI: &str = r#"
    /** The shell calls this to pass arguments: memory that stays until the request ends. */
    @Export(name = "cabi_realloc")
    public static int cabiRealloc(int old, int oldSize, int align, int newSize) {
        int p = Abi.alloc(newSize, align);
        if (old != 0) {
            Address.moveMemoryBlock(Address.fromInt(old), Address.fromInt(p), oldSize < newSize ? oldSize : newSize);
        }
        return p;
    }

    /** The canonical ABI over TeaVM's linear memory: values at addresses, strings in UTF-16. */
    static final class Abi {
        private Abi() {}

        private static boolean booted;

        /**
         * Before an export runs: TeaVM initializes String on first use, and
         * an inlined String method can skip that and find "" still null.
         */
        static void boot() {
            if (!booted) {
                booted = true;
                new StringBuilder().append(booted).toString();
            }
        }

        /** `size` bytes aligned to `align`. Each request runs in a fresh instance, so nothing is freed. */
        static int alloc(int size, int align) {
            if (size == 0) {
                return align;
            }
            int p = Heap.alloc(size + align - 1).toInt();
            if (p == 0) {
                throw new OutOfMemoryError();
            }
            return (p + align - 1) & -align;
        }

        private static Address at(int a) {
            return Address.fromInt(a);
        }

        static boolean liftBool(int a) {
            return at(a).getByte() != 0;
        }

        static int liftU8(int a) {
            return at(a).getByte() & 0xff;
        }

        static int liftS8(int a) {
            return at(a).getByte();
        }

        static int liftU16(int a) {
            return at(a).getChar();
        }

        static int liftS16(int a) {
            return at(a).getShort();
        }

        static int liftI32(int a) {
            return at(a).getInt();
        }

        static long liftI64(int a) {
            return at(a).getLong();
        }

        static float liftF32(int a) {
            return at(a).getFloat();
        }

        static double liftF64(int a) {
            return at(a).getDouble();
        }

        static String liftStr(int ptr, int len) {
            char[] chars = new char[len];
            for (int i = 0; i < len; i++) {
                chars[i] = at(ptr + 2 * i).getChar();
            }
            return new String(chars);
        }

        static String liftStrAt(int a) {
            return liftStr(liftI32(a), liftI32(a + 4));
        }

        static <T> List<T> liftList(int ptr, int len, int size, IntFunction<T> item) {
            List<T> out = new ArrayList<>(len);
            for (int i = 0; i < len; i++) {
                out.add(item.apply(ptr + i * size));
            }
            return out;
        }

        static <T> List<T> liftListAt(int a, int size, IntFunction<T> item) {
            return liftList(liftI32(a), liftI32(a + 4), size, item);
        }

        static <T> Optional<T> liftOptionAt(int a, int offset, IntFunction<T> value) {
            return liftBool(a) ? Optional.of(value.apply(a + offset)) : Optional.empty();
        }

        static void lowerU8(int a, int v) {
            at(a).putByte((byte) v);
        }

        static void lowerU16(int a, int v) {
            at(a).putShort((short) v);
        }

        static void lowerI32(int a, int v) {
            at(a).putInt(v);
        }

        static void lowerI64(int a, long v) {
            at(a).putLong(v);
        }

        static void lowerF32(int a, float v) {
            at(a).putFloat(v);
        }

        static void lowerF64(int a, double v) {
            at(a).putDouble(v);
        }

        /**
         * The string in UTF-16, as the shell takes it. A Java string can hold
         * half a surrogate pair, which a WIT string can't: that half goes as
         * U+FFFD, so the length stays. (Range checks, not Character's
         * methods: those may load TeaVM's Unicode tables.)
         */
        static int lowerStr(String s) {
            int len = s.length();
            int p = alloc(2 * len, 2);
            for (int i = 0; i < len; i++) {
                char c = s.charAt(i);
                if (c >= 0xD800 && c <= 0xDFFF) {
                    boolean high = c <= 0xDBFF;
                    char next = i + 1 < len ? s.charAt(i + 1) : 0;
                    char before = i > 0 ? s.charAt(i - 1) : 0;
                    boolean paired = high ? next >= 0xDC00 && next <= 0xDFFF : before >= 0xD800 && before <= 0xDBFF;
                    if (!paired) {
                        c = 0xFFFD;
                    }
                }
                at(p + 2 * i).putChar(c);
            }
            return p;
        }

        static void lowerStrAt(int a, String s) {
            lowerI32(a, lowerStr(s));
            lowerI32(a + 4, s.length());
        }

        static <T> int lowerList(List<T> list, int size, int align, ObjIntConsumer<T> item) {
            int p = alloc(list.size() * size, align);
            for (int i = 0; i < list.size(); i++) {
                item.accept(list.get(i), p + i * size);
            }
            return p;
        }

        static <T> void lowerListAt(int a, List<T> list, int size, int align, ObjIntConsumer<T> item) {
            lowerI32(a, lowerList(list, size, align, item));
            lowerI32(a + 4, list.size());
        }

        static <T> void lowerOptionAt(int a, Optional<T> o, int offset, ObjIntConsumer<T> value) {
            lowerU8(a, o.isPresent() ? 1 : 0);
            if (o.isPresent()) {
                value.accept(o.get(), a + offset);
            }
        }
    }
"#;

pub fn generate(resolve: &Resolve, world: WorldId) -> Result<String> {
    let mut sizes = SizeAlign::default();
    sizes.fill(resolve)?;
    let mut g = Gen { resolve, sizes, classes: BTreeMap::new(), records: HashSet::new(), tuples: BTreeSet::new(), tmp: 0 };

    let exported = exports(resolve, world);
    for w in &exported {
        let Some(id) = w.interface else { bail!("world-level export {} isn't supported for Java apps yet", w.func.name) };
        let name = g.class(id)?;
        g.classes.get_mut(&name).expect("class").export = true;
    }
    for w in imports(resolve, world) {
        let Some(id) = w.interface else { bail!("world-level function {} isn't supported for Java apps yet", w.func.name) };
        let name = g.class(id)?;
        if g.classes[&name].export {
            bail!("the WIT both imports and exports {name}, which Java apps can't have yet");
        }
        let code = g.import_fn(&w)?;
        g.classes.get_mut(&name).expect("class").body.push_str(&code);
    }
    let mut wrappers = String::new();
    let mut getters = BTreeSet::new();
    for w in &exported {
        let (decl, wrapper) = g.export_fn(w)?;
        let name = g.class(w.interface.expect("interface"))?;
        g.classes.get_mut(&name).expect("class").body.push_str(&decl);
        wrappers.push_str(&wrapper);
        getters.insert(name);
    }

    let world_name = &resolve.worlds[world].name;
    let mut out = format!("{HEADER}{IMPORTS}\n");
    writeln!(out, "/**")?;
    writeln!(out, " * The WIT world `{world_name}`: the shell's calls as Java methods, and the")?;
    writeln!(out, " * interfaces the app implements in {{@code {APP}}}. TeaVM compiles from here.")?;
    writeln!(out, " */")?;
    writeln!(out, "public final class Wit {{")?;
    writeln!(out, "    private Wit() {{}}\n")?;
    writeln!(out, "    /** TeaVM needs a main class; the app starts in the exports below. */")?;
    writeln!(out, "    public static void main(String[] args) {{}}")?;
    for n in &g.tuples {
        let params: Vec<String> = (0..*n).map(|i| format!("T{i}")).collect();
        let fields: Vec<String> = (0..*n).map(|i| format!("T{i} f{i}")).collect();
        write!(out, "\n    /** A WIT tuple of {n} values. */\n    public record Tuple{n}<{}>({}) {{}}\n", params.join(", "), fields.join(", "))?;
    }
    for (name, class) in &g.classes {
        if class.types.is_empty() && class.body.is_empty() {
            continue;
        }
        out.push('\n');
        out.push_str(&class.docs);
        if class.export {
            writeln!(out, "    public interface {name} {{")?;
        } else {
            writeln!(out, "    public static final class {name} {{")?;
            writeln!(out, "        private {name}() {{}}")?;
        }
        for part in [&class.types, &class.body] {
            if !part.is_empty() {
                out.push('\n');
                out.push_str(part.trim_end_matches('\n'));
                out.push('\n');
            }
        }
        writeln!(out, "    }}")?;
    }
    if !exported.is_empty() {
        writeln!(out, "\n    private static {APP} app;\n")?;
        writeln!(
            out,
            "    private static {APP} app() {{\n        if (app == null) {{\n            app = new {APP}();\n        }}\n        return app;\n    }}"
        )?;
        for name in &getters {
            writeln!(out, "\n    /** {{@code {APP}}} must implement {name}. */\n    private static {name} ${name}() {{\n        return app();\n    }}")?;
        }
        out.push('\n');
        out.push_str(wrappers.trim_end_matches('\n'));
        out.push('\n');
    }
    out.push_str(ABI);
    out.push_str("}\n");
    Ok(out)
}

#[derive(Default)]
struct Class {
    /// An exported interface: a Java interface the app implements.
    export: bool,
    docs: String,
    /// Its records.
    types: String,
    /// Its functions.
    body: String,
}

struct Gen<'a> {
    resolve: &'a Resolve,
    sizes: SizeAlign,
    classes: BTreeMap<String, Class>,
    records: HashSet<TypeId>,
    /// Arities of the tuples used.
    tuples: BTreeSet<usize>,
    /// For fresh lambda parameter names.
    tmp: usize,
}

fn unsupported(what: &str) -> anyhow::Error {
    anyhow::anyhow!("{what} in the WIT isn't supported for Java apps yet")
}

impl Gen<'_> {
    /// The class of an interface, created on first use.
    fn class(&mut self, id: InterfaceId) -> Result<String> {
        let iface = &self.resolve.interfaces[id];
        let name = pascal(iface.name.as_deref().ok_or_else(|| unsupported("an anonymous interface"))?);
        if name == "Abi" || name == "Wit" || name.starts_with("Tuple") {
            bail!("an interface named {name} clashes with the generated Java");
        }
        if !self.classes.contains_key(&name) {
            let docs = doc(&iface.docs, "    ");
            self.classes.insert(name.clone(), Class { docs, ..Class::default() });
        }
        Ok(name)
    }

    fn fresh(&mut self) -> usize {
        self.tmp += 1;
        self.tmp
    }

    /// The type with aliases (`use types.{request}`) followed.
    fn deref(&self, ty: &Type) -> Type {
        let mut ty = *ty;
        while let Type::Id(id) = ty {
            match &self.resolve.types[id].kind {
                TypeDefKind::Type(t) => ty = *t,
                _ => break,
            }
        }
        ty
    }

    fn size(&self, ty: &Type) -> usize {
        self.sizes.size(ty).size_wasm32()
    }

    fn align(&self, ty: &Type) -> usize {
        self.sizes.align(ty).align_wasm32()
    }

    fn offsets(&self, types: &[Type]) -> Vec<usize> {
        self.sizes.field_offsets(types.iter()).into_iter().map(|(o, _)| o.size_wasm32()).collect()
    }

    /// The Java type; `boxed` for a type argument (`List<Integer>`).
    fn java(&mut self, ty: &Type, boxed: bool) -> Result<String> {
        let pick = |plain: &str, b: &str| if boxed { b.to_string() } else { plain.to_string() };
        Ok(match self.deref(ty) {
            Type::Bool => pick("boolean", "Boolean"),
            Type::U8 | Type::S8 | Type::U16 | Type::S16 | Type::U32 | Type::S32 | Type::Char => pick("int", "Integer"),
            Type::U64 | Type::S64 => pick("long", "Long"),
            Type::F32 => pick("float", "Float"),
            Type::F64 => pick("double", "Double"),
            Type::String => "String".into(),
            Type::ErrorContext => return Err(unsupported("error-context")),
            Type::Id(id) => match &self.resolve.types[id].kind {
                TypeDefKind::Record(_) => self.record(id)?,
                TypeDefKind::List(t) => format!("List<{}>", self.java(t, true)?),
                TypeDefKind::Option(t) => format!("Optional<{}>", self.java(t, true)?),
                TypeDefKind::Tuple(t) if t.types.is_empty() => return Err(unsupported("an empty tuple")),
                TypeDefKind::Tuple(t) => {
                    self.tuples.insert(t.types.len());
                    let args = t.types.iter().map(|t| self.java(t, true)).collect::<Result<Vec<_>>>()?;
                    format!("Tuple{}<{}>", t.types.len(), args.join(", "))
                }
                kind => return Err(unsupported(kind_name(kind))),
            },
        })
    }

    /// A record: emitted once into its interface's class, with functions
    /// that read it from and write it to linear memory. Returns its name as
    /// seen from Wit (`Types.Request`).
    fn record(&mut self, id: TypeId) -> Result<String> {
        let def = &self.resolve.types[id];
        let TypeDefKind::Record(r) = &def.kind else { unreachable!() };
        let name = pascal(def.name.as_deref().ok_or_else(|| unsupported("an anonymous record"))?);
        let TypeOwner::Interface(owner) = def.owner else { return Err(unsupported("a record outside an interface")) };
        let class = self.class(owner)?;
        let qualified = format!("{class}.{name}");
        if !self.records.insert(id) {
            return Ok(qualified);
        }
        let (docs, fields) = (def.docs.clone(), r.fields.clone());
        let mut code = String::new();
        let mut text = docs.contents.as_deref().unwrap_or("").trim().to_string();
        for f in &fields {
            if let Some(d) = f.docs.contents.as_deref() {
                write!(text, "\n@param {} {}", field_ident(&f.name), d.trim().replace('\n', " "))?;
            }
        }
        code.push_str(&doc(&Docs { contents: (!text.trim().is_empty()).then(|| text.trim().to_string()) }, "        "));
        let mut components = Vec::new();
        for f in &fields {
            components.push(format!("{} {}", self.java(&f.ty, false)?, field_ident(&f.name)));
        }
        writeln!(code, "        public record {name}(\n                {}) {{}}\n", components.join(",\n                "))?;

        let types: Vec<Type> = fields.iter().map(|f| f.ty).collect();
        let offsets = self.offsets(&types);
        let mut lifts = Vec::new();
        for (t, o) in types.iter().zip(&offsets) {
            lifts.push(self.lift_mem(t, &at("$a", *o))?);
        }
        writeln!(code, "        static {name} lift{name}(int $a) {{\n            return new {name}({});\n        }}\n", lifts.join(", "))?;
        let mut lowers = String::new();
        for (f, o) in fields.iter().zip(&offsets) {
            writeln!(lowers, "            {}", self.lower_mem(&f.ty, &format!("$v.{}()", field_ident(&f.name)), &at("$a", *o))?)?;
        }
        writeln!(code, "        static void lower{name}(int $a, {name} $v) {{\n{lowers}        }}\n")?;
        self.classes.get_mut(&class).expect("class").types.push_str(&code);
        Ok(qualified)
    }

    /// A Java expression for the value at address `a`.
    fn lift_mem(&mut self, ty: &Type, a: &str) -> Result<String> {
        Ok(match self.deref(ty) {
            Type::Bool => format!("Abi.liftBool({a})"),
            Type::U8 => format!("Abi.liftU8({a})"),
            Type::S8 => format!("Abi.liftS8({a})"),
            Type::U16 => format!("Abi.liftU16({a})"),
            Type::S16 => format!("Abi.liftS16({a})"),
            Type::U32 | Type::S32 | Type::Char => format!("Abi.liftI32({a})"),
            Type::U64 | Type::S64 => format!("Abi.liftI64({a})"),
            Type::F32 => format!("Abi.liftF32({a})"),
            Type::F64 => format!("Abi.liftF64({a})"),
            Type::String => format!("Abi.liftStrAt({a})"),
            Type::ErrorContext => return Err(unsupported("error-context")),
            Type::Id(id) => match &self.resolve.types[id].kind {
                TypeDefKind::Record(_) => {
                    let name = self.record(id)?;
                    let (class, record) = name.split_once('.').expect("qualified");
                    format!("{class}.lift{record}({a})")
                }
                TypeDefKind::List(t) => {
                    let x = format!("$a{}", self.fresh());
                    let item = self.lift_mem(t, &x)?;
                    format!("Abi.liftListAt({a}, {}, {x} -> {item})", self.size(t))
                }
                TypeDefKind::Option(t) => {
                    let x = format!("$a{}", self.fresh());
                    let value = self.lift_mem(t, &x)?;
                    format!("Abi.liftOptionAt({a}, {}, {x} -> {value})", self.align(t))
                }
                TypeDefKind::Tuple(t) => {
                    let java = self.java(ty, false)?;
                    let types = t.types.clone();
                    let offsets = self.offsets(&types);
                    let mut items = Vec::new();
                    for (t, o) in types.iter().zip(offsets) {
                        items.push(self.lift_mem(t, &at(a, o))?);
                    }
                    format!("new {java}({})", items.join(", "))
                }
                kind => return Err(unsupported(kind_name(kind))),
            },
        })
    }

    /// A Java statement that writes `v` at address `a`. `v` is evaluated
    /// more than once: a variable or a record accessor.
    fn lower_mem(&mut self, ty: &Type, v: &str, a: &str) -> Result<String> {
        Ok(match self.deref(ty) {
            Type::Bool => format!("Abi.lowerU8({a}, {v} ? 1 : 0);"),
            Type::U8 | Type::S8 => format!("Abi.lowerU8({a}, {v});"),
            Type::U16 | Type::S16 => format!("Abi.lowerU16({a}, {v});"),
            Type::U32 | Type::S32 | Type::Char => format!("Abi.lowerI32({a}, {v});"),
            Type::U64 | Type::S64 => format!("Abi.lowerI64({a}, {v});"),
            Type::F32 => format!("Abi.lowerF32({a}, {v});"),
            Type::F64 => format!("Abi.lowerF64({a}, {v});"),
            Type::String => format!("Abi.lowerStrAt({a}, {v});"),
            Type::ErrorContext => return Err(unsupported("error-context")),
            Type::Id(id) => match &self.resolve.types[id].kind {
                TypeDefKind::Record(_) => {
                    let name = self.record(id)?;
                    let (class, record) = name.split_once('.').expect("qualified");
                    format!("{class}.lower{record}({a}, {v});")
                }
                TypeDefKind::List(t) => {
                    let n = self.fresh();
                    let item = self.lower_mem(t, &format!("$e{n}"), &format!("$a{n}"))?;
                    format!("Abi.lowerListAt({a}, {v}, {}, {}, ($e{n}, $a{n}) -> {{ {item} }});", self.size(t), self.align(t))
                }
                TypeDefKind::Option(t) => {
                    let n = self.fresh();
                    let value = self.lower_mem(t, &format!("$e{n}"), &format!("$a{n}"))?;
                    format!("Abi.lowerOptionAt({a}, {v}, {}, ($e{n}, $a{n}) -> {{ {value} }});", self.align(t))
                }
                TypeDefKind::Tuple(t) => {
                    let types = t.types.clone();
                    let offsets = self.offsets(&types);
                    let mut parts = Vec::new();
                    for (i, (t, o)) in types.iter().zip(offsets).enumerate() {
                        parts.push(self.lower_mem(t, &format!("{v}.f{i}()"), &at(a, o))?);
                    }
                    parts.join(" ")
                }
                kind => return Err(unsupported(kind_name(kind))),
            },
        })
    }

    /// The core values for `v`, in the canonical ABI's flat order. `v` is
    /// evaluated more than once.
    fn flat_lower(&mut self, ty: &Type, v: &str) -> Result<Vec<(String, WasmType)>> {
        Ok(match self.deref(ty) {
            Type::Bool => vec![(format!("({v} ? 1 : 0)"), WasmType::I32)],
            Type::U8 | Type::S8 | Type::U16 | Type::S16 | Type::U32 | Type::S32 | Type::Char => vec![(v.to_string(), WasmType::I32)],
            Type::U64 | Type::S64 => vec![(v.to_string(), WasmType::I64)],
            Type::F32 => vec![(v.to_string(), WasmType::F32)],
            Type::F64 => vec![(v.to_string(), WasmType::F64)],
            Type::String => vec![(format!("Abi.lowerStr({v})"), WasmType::Pointer), (format!("{v}.length()"), WasmType::Length)],
            Type::ErrorContext => return Err(unsupported("error-context")),
            Type::Id(id) => match &self.resolve.types[id].kind {
                TypeDefKind::Record(r) => {
                    let fields = r.fields.clone();
                    let mut out = Vec::new();
                    for f in &fields {
                        out.extend(self.flat_lower(&f.ty, &format!("{v}.{}()", field_ident(&f.name)))?);
                    }
                    out
                }
                TypeDefKind::List(t) => {
                    let n = self.fresh();
                    let item = self.lower_mem(t, &format!("$e{n}"), &format!("$a{n}"))?;
                    let list = format!("Abi.lowerList({v}, {}, {}, ($e{n}, $a{n}) -> {{ {item} }})", self.size(t), self.align(t));
                    vec![(list, WasmType::Pointer), (format!("{v}.size()"), WasmType::Length)]
                }
                TypeDefKind::Option(t) => {
                    let mut out = vec![(format!("({v}.isPresent() ? 1 : 0)"), WasmType::I32)];
                    for (e, t) in self.flat_lower(t, &format!("{v}.get()"))? {
                        out.push((format!("({v}.isPresent() ? {e} : {})", zero(t)), t));
                    }
                    out
                }
                TypeDefKind::Tuple(t) => {
                    let types = t.types.clone();
                    let mut out = Vec::new();
                    for (i, t) in types.iter().enumerate() {
                        out.extend(self.flat_lower(t, &format!("{v}.f{i}()"))?);
                    }
                    out
                }
                kind => return Err(unsupported(kind_name(kind))),
            },
        })
    }

    /// A Java expression for the value in the next core values.
    fn flat_lift(&mut self, ty: &Type, values: &mut impl Iterator<Item = String>) -> Result<String> {
        let mut next = || values.next().ok_or_else(|| anyhow::anyhow!("fewer core values than the type needs"));
        Ok(match self.deref(ty) {
            Type::Bool => format!("({} != 0)", next()?),
            Type::String => {
                let (p, n) = (next()?, next()?);
                format!("Abi.liftStr({p}, {n})")
            }
            Type::ErrorContext => return Err(unsupported("error-context")),
            Type::Id(id) => match &self.resolve.types[id].kind {
                TypeDefKind::Record(r) => {
                    let name = self.record(id)?;
                    let fields = r.fields.clone();
                    let mut items = Vec::new();
                    for f in &fields {
                        items.push(self.flat_lift(&f.ty, values)?);
                    }
                    format!("new {name}({})", items.join(", "))
                }
                TypeDefKind::List(t) => {
                    let (p, n) = (next()?, next()?);
                    let x = format!("$a{}", self.fresh());
                    let item = self.lift_mem(t, &x)?;
                    format!("Abi.liftList({p}, {n}, {}, {x} -> {item})", self.size(t))
                }
                TypeDefKind::Option(t) => {
                    let d = next()?;
                    let boxed = self.java(t, true)?;
                    let value = self.flat_lift(t, values)?;
                    format!("({d} == 0 ? Optional.<{boxed}>empty() : Optional.of({value}))")
                }
                TypeDefKind::Tuple(t) => {
                    let java = self.java(ty, false)?;
                    let types = t.types.clone();
                    let mut items = Vec::new();
                    for t in &types {
                        items.push(self.flat_lift(t, values)?);
                    }
                    format!("new {java}({})", items.join(", "))
                }
                kind => return Err(unsupported(kind_name(kind))),
            },
            _ => next()?,
        })
    }

    /// An import: the native method TeaVM imports, and a public method with
    /// Java types around it.
    fn import_fn(&mut self, w: &WitFn) -> Result<String> {
        let func = w.func;
        let name = ident(&camel(&func.name));
        let raw = format!("${}", camel(&func.name));
        let mut params = Vec::new();
        for p in &func.params {
            params.push(format!("{} {}", self.java(&p.ty, false)?, ident(&camel(&p.name))));
        }
        let ret = match &func.result {
            Some(t) => self.java(t, false)?,
            None => "void".into(),
        };
        let core_params: Vec<String> = w.sig.params.iter().enumerate().map(|(i, t)| format!("{} $p{i}", jtype(t))).collect();
        let core_ret = match (w.sig.retptr, w.sig.results.as_slice()) {
            (true, _) | (false, []) => "void",
            (false, [t]) => jtype(t),
            _ => bail!("{} returns more than one core value", func.name),
        };

        let mut body = String::new();
        let mut args = Vec::new();
        if w.sig.indirect_params {
            let types: Vec<Type> = func.params.iter().map(|p| p.ty).collect();
            let info = self.sizes.params(types.iter());
            writeln!(body, "            int $args = Abi.alloc({}, {});", info.size.size_wasm32(), info.align.align_wasm32())?;
            for (p, o) in func.params.iter().zip(self.offsets(&types)) {
                writeln!(body, "            {}", self.lower_mem(&p.ty, &ident(&camel(&p.name)), &at("$args", o))?)?;
            }
            args.push("$args".to_string());
        } else {
            for p in &func.params {
                args.extend(self.flat_lower(&p.ty, &ident(&camel(&p.name)))?.into_iter().map(|(e, _)| e));
            }
        }
        if w.sig.retptr {
            let t = func.result.as_ref().expect("a result");
            writeln!(body, "            int $ret = Abi.alloc({}, {});", self.size(t), self.align(t))?;
            args.push("$ret".into());
        }
        if args.len() != w.sig.params.len() {
            bail!("{}: {} core values for {} parameters", func.name, args.len(), w.sig.params.len());
        }
        let call = format!("{raw}({})", args.join(", "));
        match (&func.result, w.sig.retptr) {
            (None, _) => writeln!(body, "            {call};")?,
            (Some(t), true) => {
                writeln!(body, "            {call};")?;
                writeln!(body, "            return {};", self.lift_mem(t, "$ret")?)?;
            }
            (Some(t), false) => {
                writeln!(body, "            {core_ret} $r = {call};")?;
                writeln!(body, "            return {};", self.flat_lift(t, &mut std::iter::once("$r".to_string()))?)?;
            }
        }

        let mut code = String::new();
        writeln!(code, "        @Import(module = \"{}\", name = \"{}\")", w.module, w.name)?;
        writeln!(code, "        private static native {core_ret} {raw}({});\n", core_params.join(", "))?;
        code.push_str(&doc(&func.docs, "        "));
        writeln!(code, "        public static {ret} {name}({}) {{\n{body}        }}\n", params.join(", "))?;
        Ok(code)
    }

    /// An export: the method in the interface the app implements, and the
    /// exported wrapper that reads the shell's arguments and calls it.
    fn export_fn(&mut self, w: &WitFn) -> Result<(String, String)> {
        let func = w.func;
        let iface = self.class(w.interface.expect("interface"))?;
        let method = ident(&camel(&func.name));
        let mut params = Vec::new();
        for p in &func.params {
            params.push(format!("{} {}", self.java(&p.ty, false)?, ident(&camel(&p.name))));
        }
        let ret = match &func.result {
            Some(t) => self.java(t, false)?,
            None => "void".into(),
        };
        let mut decl = doc(&func.docs, "        ");
        writeln!(decl, "        {ret} {method}({});\n", params.join(", "))?;

        let core_params: Vec<String> = w.sig.params.iter().enumerate().map(|(i, t)| format!("{} $p{i}", jtype(t))).collect();
        let core_ret = match w.sig.results.as_slice() {
            [] => "void",
            [t] => jtype(t),
            _ => bail!("{} returns more than one core value", func.name),
        };
        let mut args = Vec::new();
        if w.sig.indirect_params {
            let types: Vec<Type> = func.params.iter().map(|p| p.ty).collect();
            for (t, o) in types.iter().zip(self.offsets(&types)) {
                args.push(self.lift_mem(t, &at("$p0", o))?);
            }
        } else {
            let mut values = (0..w.sig.params.len()).map(|i| format!("$p{i}"));
            for p in &func.params {
                args.push(self.flat_lift(&p.ty, &mut values)?);
            }
        }
        let call = format!("${iface}().{method}({})", args.join(", "));
        let mut body = String::new();
        match (&func.result, w.sig.retptr) {
            (None, _) => writeln!(body, "        {call};")?,
            (Some(t), false) => {
                let [(value, _)] = <[_; 1]>::try_from(self.flat_lower(t, "$r")?).map_err(|_| anyhow::anyhow!("{}: one core result expected", func.name))?;
                writeln!(body, "        {ret} $r = {call};\n        return {value};")?;
            }
            (Some(t), true) => {
                writeln!(body, "        {ret} $r = {call};")?;
                writeln!(body, "        int $ret = Abi.alloc({}, {});", self.size(t), self.align(t))?;
                writeln!(body, "        {}", self.lower_mem(t, "$r", "$ret")?)?;
                writeln!(body, "        return $ret;")?;
            }
        }
        let wrapper = format!(
            "    @Export(name = \"{}\")\n    public static {core_ret} {}${method}({}) {{\n        Abi.boot();\n{body}    }}\n\n",
            w.name,
            lower_first(&iface),
            core_params.join(", ")
        );
        Ok((decl, wrapper))
    }
}

/// `a` plus `offset`, without `+ 0`.
fn at(a: &str, offset: usize) -> String {
    if offset == 0 { a.to_string() } else { format!("{a} + {offset}") }
}

fn jtype(t: &WasmType) -> &'static str {
    match t {
        WasmType::I32 | WasmType::Pointer | WasmType::Length => "int",
        WasmType::I64 | WasmType::PointerOrI64 => "long",
        WasmType::F32 => "float",
        WasmType::F64 => "double",
    }
}

fn zero(t: WasmType) -> &'static str {
    match t {
        WasmType::I32 | WasmType::Pointer | WasmType::Length => "0",
        WasmType::I64 | WasmType::PointerOrI64 => "0L",
        WasmType::F32 => "0f",
        WasmType::F64 => "0d",
    }
}

fn kind_name(kind: &TypeDefKind) -> &'static str {
    match kind {
        TypeDefKind::Variant(_) => "a variant",
        TypeDefKind::Enum(_) => "an enum",
        TypeDefKind::Flags(_) => "flags",
        TypeDefKind::Result(_) => "a result",
        TypeDefKind::Resource | TypeDefKind::Handle(_) => "a resource",
        TypeDefKind::Future(_) => "a future",
        TypeDefKind::Stream(_) => "a stream",
        _ => "this type",
    }
}

/// WIT docs as Javadoc.
fn doc(docs: &Docs, indent: &str) -> String {
    let Some(text) = docs.contents.as_deref().map(str::trim).filter(|t| !t.is_empty()) else { return String::new() };
    let text = text.replace("*/", "*&#47;");
    let lines: Vec<&str> = text.lines().collect();
    if let [line] = lines.as_slice() {
        return format!("{indent}/** {line} */\n");
    }
    let mut out = format!("{indent}/**\n");
    for line in lines {
        if line.is_empty() {
            out.push_str(&format!("{indent} *\n"));
        } else {
            out.push_str(&format!("{indent} * {line}\n"));
        }
    }
    out.push_str(&format!("{indent} */\n"));
    out
}

fn camel(name: &str) -> String {
    let mut out = String::new();
    for (i, part) in name.split('-').enumerate() {
        if i == 0 {
            out.push_str(part);
        } else {
            out.push_str(&upper_first(part));
        }
    }
    out
}

fn pascal(name: &str) -> String {
    upper_first(&camel(name))
}

fn upper_first(s: &str) -> String {
    let mut c = s.chars();
    c.next().map(|f| f.to_uppercase().chain(c).collect()).unwrap_or_default()
}

fn lower_first(s: &str) -> String {
    let mut c = s.chars();
    c.next().map(|f| f.to_lowercase().chain(c).collect()).unwrap_or_default()
}

