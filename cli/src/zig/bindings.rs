//! WIT -> Zig, written to the app's `bindings/wit.zig`:
//!
//!   - per interface a namespace (`wit.page`, `wit.kv`) with its records and
//!     its imports as Zig functions taking and returning Zig values
//!     (`wit.page.setHtml(name, html)`, `wit.kv.get(key) ?[]const u8`)
//!   - `wit.exports(App)`, which exports the world's functions for the
//!     WebAssembly component: each reads its arguments and calls the app's
//!     implementation, `App.handler.start(...)`
//!   - `cabi_realloc` and `wit.allocator`
//!
//! Zig reaches the canonical ABI directly: an import is an `extern` function
//! of its WIT module and name, records and lists are read in place through
//! `extern struct`s with the ABI's layout. Strings and byte lists the shell
//! passes are not copied; other lists are lifted into new slices.
//!
//! Supported: bool, integers, floats, char, string, list, option, tuple and
//! record. Anything else in the WIT is an error naming the type.

use std::collections::{BTreeMap, HashMap, HashSet};
use std::fmt::Write as _;

use anyhow::{Result, bail};
use wit_parser::abi::WasmType;
use wit_parser::{Docs, Resolve, Type, TypeDefKind, TypeId, TypeOwner, WorldId};

use crate::ts::{WitFn, exports, imports};

/// The file in `bindings/`, the app's `wit` module.
pub const FILE: &str = "wit.zig";

const HEADER: &str = "// Generated by `appos build` from wit/. Don't edit: every build rewrites it.\n";

const PRELUDE: &str = r#"
const std = @import("std");

/// The allocator for values the shell passes in (lists, options of lists)
/// and for the app: each request runs in a fresh instance, so nothing needs
/// to be freed.
pub const allocator = std.heap.wasm_allocator;

/// Canonical-ABI layouts, as the shell reads and writes them.
pub const Str = extern struct { ptr: [*]const u8, len: usize };
pub fn List(comptime T: type) type {
    return extern struct { ptr: [*]const T, len: usize };
}
pub fn Option(comptime T: type) type {
    return extern struct { is_some: u8, value: T };
}

fn str(s: []const u8) Str {
    return .{ .ptr = s.ptr, .len = s.len };
}

fn alloc(comptime T: type, n: usize) []T {
    return allocator.alloc(T, n) catch @trap();
}

/// The shell calls this to put arguments and results into the app's memory.
fn cabiRealloc(old: ?[*]u8, old_size: usize, alignment: usize, new_size: usize) callconv(.c) ?[*]u8 {
    if (new_size == 0) return @ptrFromInt(alignment);
    const p = allocator.rawAlloc(new_size, .fromByteUnits(alignment), @returnAddress()) orelse @trap();
    if (old) |o| @memcpy(p[0..@min(old_size, new_size)], o[0..@min(old_size, new_size)]);
    return p;
}
"#;

pub fn generate(resolve: &Resolve, world: WorldId) -> Result<String> {
    let mut g = Gen {
        resolve,
        namespaces: BTreeMap::new(),
        helpers: String::new(),
        helper_names: HashMap::new(),
        records: HashSet::new(),
        tuples: HashSet::new(),
        tmp: 0,
    };

    for w in imports(resolve, world) {
        let Some(id) = w.interface else { bail!("world-level function {} isn't supported for Zig apps yet", w.func.name) };
        let ns = snake(resolve.interfaces[id].name.as_deref().unwrap_or("interface"));
        let code = g.import_fn(&w)?;
        let n = g.namespaces.entry(ns).or_default();
        n.raw.push_str(&code.0);
        n.body.push_str(&code.1);
    }

    let mut exports_body = String::new();
    let mut exported = String::new();
    for w in exports(resolve, world) {
        let Some(id) = w.interface else { bail!("world-level export {} isn't supported for Zig apps yet", w.func.name) };
        let ns = ident(&snake(resolve.interfaces[id].name.as_deref().unwrap_or("interface")));
        let local = format!("{}_{}", snake(resolve.interfaces[id].name.as_deref().unwrap_or("interface")), snake(&w.func.name));
        exports_body.push_str(&g.export_fn(&w, &ns, &local)?);
        writeln!(exported, "    @export(&S.{local}, .{{ .name = \"{}\" }});", w.name)?;
    }

    let mut out = format!("{HEADER}{PRELUDE}");
    for (name, ns) in &g.namespaces {
        write!(out, "\npub const {} = struct {{\n", ident(name))?;
        if !ns.raw.is_empty() {
            write!(out, "    const raw = struct {{\n{}    }};\n", ns.raw)?;
        }
        out.push_str(&ns.body);
        out.push_str("};\n");
    }
    write!(
        out,
        "\n/// Exports the world's functions from the component, implemented by\n\
         /// `App`, the app's root file: `comptime {{ wit.exports(@This()); }}`.\n\
         pub fn exports(comptime App: type) void {{\n    const S = struct {{\n{exports_body}    }};\n{exported}    @export(&cabiRealloc, .{{ .name = \"cabi_realloc\" }});\n}}\n"
    )?;
    if !g.helpers.is_empty() {
        write!(out, "\n// Lifting and lowering of anonymous types.\n{}", g.helpers)?;
    }
    Ok(out)
}

#[derive(Default)]
struct Namespace {
    /// The `extern` declarations, in `raw`.
    raw: String,
    /// Records and functions.
    body: String,
}

struct Gen<'a> {
    resolve: &'a Resolve,
    namespaces: BTreeMap<String, Namespace>,
    /// Functions for anonymous types (lists, options, tuples), by the Zig
    /// type they lift or lower.
    helpers: String,
    helper_names: HashMap<String, String>,
    records: HashSet<TypeId>,
    tuples: HashSet<usize>,
    tmp: usize,
}

fn unsupported(what: &str) -> anyhow::Error {
    anyhow::anyhow!("{what} in the WIT isn't supported for Zig apps yet")
}

/// A core value: its Zig expression and type.
struct Flat {
    expr: String,
    ty: &'static str,
}

impl Gen<'_> {
    /// The type with aliases followed.
    fn deref(&self, ty: &Type) -> Result<DType> {
        let mut ty = *ty;
        loop {
            match ty {
                Type::Id(id) => match &self.resolve.types[id].kind {
                    TypeDefKind::Type(t) => ty = *t,
                    _ => return Ok(DType::Id(id)),
                },
                t => return Ok(DType::Prim(t)),
            }
        }
    }

    /// Whether the Zig type and the ABI layout are the same, so a list of it
    /// can be used in place.
    fn same_layout(&self, ty: &Type) -> Result<bool> {
        Ok(matches!(
            self.deref(ty)?,
            DType::Prim(Type::U8 | Type::U16 | Type::U32 | Type::U64 | Type::S8 | Type::S16 | Type::S32 | Type::S64 | Type::F32 | Type::F64)
        ))
    }

    /// The type the app sees.
    fn zig(&mut self, ty: &Type) -> Result<String> {
        Ok(match self.deref(ty)? {
            DType::Prim(p) => prim(p, false)?.into(),
            DType::Id(id) => {
                let def = &self.resolve.types[id];
                match &def.kind {
                    TypeDefKind::Record(_) => self.record(id)?.0,
                    TypeDefKind::List(t) => format!("[]const {}", self.zig(t)?),
                    TypeDefKind::Option(t) => format!("?{}", self.zig(t)?),
                    TypeDefKind::Tuple(t) => {
                        let types = t.types.iter().map(|t| self.zig(t)).collect::<Result<Vec<_>>>()?;
                        format!("@Tuple(&.{{ {} }})", types.join(", "))
                    }
                    kind => return Err(unsupported(kind_name(kind))),
                }
            }
        })
    }

    /// The canonical-ABI layout of the type.
    fn raw(&mut self, ty: &Type) -> Result<String> {
        Ok(match self.deref(ty)? {
            DType::Prim(p) => prim(p, true)?.into(),
            DType::Id(id) => {
                let def = &self.resolve.types[id];
                match &def.kind {
                    TypeDefKind::Record(_) => self.record(id)?.1,
                    TypeDefKind::List(t) => format!("List({})", self.raw(t)?),
                    TypeDefKind::Option(t) => format!("Option({})", self.raw(t)?),
                    TypeDefKind::Tuple(t) => {
                        let n = t.types.len();
                        self.tuple_raw(n)?;
                        let types = t.types.iter().map(|t| self.raw(t)).collect::<Result<Vec<_>>>()?;
                        format!("RawTuple{n}({})", types.join(", "))
                    }
                    kind => return Err(unsupported(kind_name(kind))),
                }
            }
        })
    }

    fn tuple_raw(&mut self, n: usize) -> Result<()> {
        if self.tuples.insert(n) {
            let params: Vec<String> = (0..n).map(|i| format!("comptime T{i}: type")).collect();
            let fields: Vec<String> = (0..n).map(|i| format!("f{i}: T{i}")).collect();
            write!(self.helpers, "fn RawTuple{n}({}) type {{\n    return extern struct {{ {} }};\n}}\n", params.join(", "), fields.join(", "))?;
        }
        Ok(())
    }

    /// A record: emitted once into its interface's namespace. Returns its
    /// Zig type, raw type and lift function.
    fn record(&mut self, id: TypeId) -> Result<(String, String, String)> {
        let def = &self.resolve.types[id];
        let TypeDefKind::Record(r) = &def.kind else { unreachable!() };
        let name = def.name.as_deref().ok_or_else(|| unsupported("an anonymous record"))?;
        let TypeOwner::Interface(owner) = def.owner else { return Err(unsupported("a record outside an interface")) };
        let ns = snake(self.resolve.interfaces[owner].name.as_deref().unwrap_or("interface"));
        let (zig, raw, lift) = (pascal(name), format!("Raw{}", pascal(name)), format!("lift{}", pascal(name)));
        let qualified = (format!("{}.{zig}", ident(&ns)), format!("{}.{raw}", ident(&ns)), format!("{}.{lift}", ident(&ns)));
        if !self.records.insert(id) {
            return Ok(qualified);
        }
        let mut code = String::new();
        code.push_str(&doc(&def.docs, "    "));
        writeln!(code, "    pub const {zig} = struct {{")?;
        for f in &r.fields {
            code.push_str(&doc(&f.docs, "        "));
            writeln!(code, "        {}: {},", ident(&snake(&f.name)), self.zig(&f.ty)?)?;
        }
        writeln!(code, "    }};")?;
        writeln!(code, "    /// {zig} in the canonical ABI's layout.")?;
        writeln!(code, "    pub const {raw} = extern struct {{")?;
        for f in &r.fields {
            writeln!(code, "        {}: {},", ident(&snake(&f.name)), self.raw(&f.ty)?)?;
        }
        writeln!(code, "    }};")?;
        writeln!(code, "    pub fn {lift}(r: {raw}) {zig} {{\n        return .{{")?;
        for f in &r.fields {
            let field = ident(&snake(&f.name));
            writeln!(code, "            .{field} = {},", self.lift(&f.ty, &format!("r.{field}"))?)?;
        }
        writeln!(code, "        }};\n    }}")?;
        self.namespaces.entry(ns).or_default().body.push_str(&code);
        Ok(qualified)
    }

    /// A helper function, emitted once per type: `make` writes its body.
    fn helper(&mut self, key: String, prefix: &str, make: impl FnOnce(&mut Self, &str) -> Result<String>) -> Result<String> {
        if let Some(name) = self.helper_names.get(&key) {
            return Ok(name.clone());
        }
        let name = format!("{prefix}{}", self.helper_names.len());
        self.helper_names.insert(key, name.clone());
        let code = make(self, &name)?;
        self.helpers.push_str(&code);
        Ok(name)
    }

    /// The Zig value of `expr`, which has the raw layout.
    fn lift(&mut self, ty: &Type, expr: &str) -> Result<String> {
        Ok(match self.deref(ty)? {
            DType::Prim(Type::Bool) => format!("({expr} != 0)"),
            DType::Prim(Type::Char) => format!("@as(u21, @intCast({expr}))"),
            DType::Prim(Type::String) => format!("{expr}.ptr[0..{expr}.len]"),
            DType::Prim(_) => expr.to_string(),
            DType::Id(id) => match &self.resolve.types[id].kind {
                TypeDefKind::Record(_) => format!("{}({expr})", self.record(id)?.2),
                TypeDefKind::List(t) if self.same_layout(t)? => format!("{expr}.ptr[0..{expr}.len]"),
                TypeDefKind::List(t) => {
                    let (z, r) = (self.zig(t)?, self.raw(t)?);
                    let t = *t;
                    let f = self.helper(format!("lift []const {z}"), "liftList", |g, name| {
                        let item = g.lift(&t, "item")?;
                        Ok(format!(
                            "fn {name}(l: List({r})) []const {z} {{\n    const out = alloc({z}, l.len);\n    for (out, l.ptr[0..l.len]) |*o, item| o.* = {item};\n    return out;\n}}\n"
                        ))
                    })?;
                    format!("{f}({expr})")
                }
                TypeDefKind::Option(t) => {
                    let (z, r) = (self.zig(t)?, self.raw(t)?);
                    let t = *t;
                    let f = self.helper(format!("lift ?{z}"), "liftOption", |g, name| {
                        let value = g.lift(&t, "o.value")?;
                        Ok(format!("fn {name}(o: Option({r})) ?{z} {{\n    return if (o.is_some != 0) {value} else null;\n}}\n"))
                    })?;
                    format!("{f}({expr})")
                }
                TypeDefKind::Tuple(tuple) => {
                    let z = self.zig(ty)?;
                    let r = self.raw(ty)?;
                    let types = tuple.types.clone();
                    let f = self.helper(format!("lift {z}"), "liftTuple", |g, name| {
                        let items = types.iter().enumerate().map(|(i, t)| g.lift(t, &format!("t.f{i}"))).collect::<Result<Vec<_>>>()?;
                        Ok(format!("fn {name}(t: {r}) {z} {{\n    return .{{ {} }};\n}}\n", items.join(", ")))
                    })?;
                    format!("{f}({expr})")
                }
                kind => return Err(unsupported(kind_name(kind))),
            },
        })
    }

    /// The raw layout of `expr`, a Zig value.
    fn lower(&mut self, ty: &Type, expr: &str) -> Result<String> {
        Ok(match self.deref(ty)? {
            DType::Prim(Type::Bool) => format!("@intFromBool({expr})"),
            DType::Prim(Type::Char) => format!("@as(u32, {expr})"),
            DType::Prim(Type::String) => format!("str({expr})"),
            DType::Prim(_) => expr.to_string(),
            DType::Id(id) => match &self.resolve.types[id].kind {
                TypeDefKind::Record(r) => {
                    let raw = self.record(id)?.1;
                    let fields = r.fields.clone();
                    let mut parts = Vec::new();
                    for f in &fields {
                        let field = ident(&snake(&f.name));
                        parts.push(format!(".{field} = {}", self.lower(&f.ty, &format!("{expr}.{field}"))?));
                    }
                    format!("{raw}{{ {} }}", parts.join(", "))
                }
                TypeDefKind::List(t) if self.same_layout(t)? => format!(".{{ .ptr = {expr}.ptr, .len = {expr}.len }}"),
                TypeDefKind::List(t) => {
                    let (z, r) = (self.zig(t)?, self.raw(t)?);
                    let t = *t;
                    let f = self.helper(format!("lower []const {z}"), "lowerList", |g, name| {
                        let item = g.lower(&t, "item")?;
                        Ok(format!(
                            "fn {name}(l: []const {z}) List({r}) {{\n    const out = alloc({r}, l.len);\n    for (out, l) |*o, item| o.* = {item};\n    return .{{ .ptr = out.ptr, .len = out.len }};\n}}\n"
                        ))
                    })?;
                    format!("{f}({expr})")
                }
                TypeDefKind::Option(t) => {
                    let (z, r) = (self.zig(t)?, self.raw(t)?);
                    let t = *t;
                    let f = self.helper(format!("lower ?{z}"), "lowerOption", |g, name| {
                        let value = g.lower(&t, "v")?;
                        Ok(format!(
                            "fn {name}(o: ?{z}) Option({r}) {{\n    return if (o) |v| .{{ .is_some = 1, .value = {value} }} else .{{ .is_some = 0, .value = undefined }};\n}}\n"
                        ))
                    })?;
                    format!("{f}({expr})")
                }
                TypeDefKind::Tuple(tuple) => {
                    let z = self.zig(ty)?;
                    let r = self.raw(ty)?;
                    let types = tuple.types.clone();
                    let f = self.helper(format!("lower {z}"), "lowerTuple", |g, name| {
                        let items =
                            types.iter().enumerate().map(|(i, t)| Ok(format!(".f{i} = {}", g.lower(t, &format!("t[{i}]"))?))).collect::<Result<Vec<_>>>()?;
                        Ok(format!("fn {name}(t: {z}) {r} {{\n    return .{{ {} }};\n}}\n", items.join(", ")))
                    })?;
                    format!("{f}({expr})")
                }
                kind => return Err(unsupported(kind_name(kind))),
            },
        })
    }

    /// The core values of `expr`, a Zig value, as the canonical ABI
    /// flattens it; statements that compute them go into `stmts`.
    fn flat_lower(&mut self, ty: &Type, expr: &str, stmts: &mut String, indent: &str) -> Result<Vec<Flat>> {
        let one = |expr: String, ty| vec![Flat { expr, ty }];
        Ok(match self.deref(ty)? {
            DType::Prim(Type::Bool) => one(format!("@as(u32, @intFromBool({expr}))"), "u32"),
            DType::Prim(Type::U8 | Type::U16 | Type::U32) => one(format!("@as(u32, {expr})"), "u32"),
            DType::Prim(Type::S8 | Type::S16 | Type::S32) => one(format!("@as(u32, @bitCast(@as(i32, {expr})))"), "u32"),
            DType::Prim(Type::U64) => one(expr.to_string(), "u64"),
            DType::Prim(Type::S64) => one(format!("@as(u64, @bitCast({expr}))"), "u64"),
            DType::Prim(Type::F32) => one(expr.to_string(), "f32"),
            DType::Prim(Type::F64) => one(expr.to_string(), "f64"),
            DType::Prim(Type::Char) => one(format!("@as(u32, {expr})"), "u32"),
            DType::Prim(Type::String) => {
                vec![Flat { expr: format!("@intFromPtr({expr}.ptr)"), ty: "usize" }, Flat { expr: format!("{expr}.len"), ty: "usize" }]
            }
            DType::Prim(t) => return Err(unsupported(&format!("{t:?}"))),
            DType::Id(id) => match &self.resolve.types[id].kind {
                TypeDefKind::Record(r) => {
                    let fields = r.fields.clone();
                    let mut out = Vec::new();
                    for f in &fields {
                        out.extend(self.flat_lower(&f.ty, &format!("{expr}.{}", ident(&snake(&f.name))), stmts, indent)?);
                    }
                    out
                }
                TypeDefKind::Tuple(t) => {
                    let types = t.types.clone();
                    let mut out = Vec::new();
                    for (i, t) in types.iter().enumerate() {
                        out.extend(self.flat_lower(t, &format!("{expr}[{i}]"), stmts, indent)?);
                    }
                    out
                }
                TypeDefKind::List(_) => {
                    let n = self.tmp;
                    self.tmp += 1;
                    let lowered = self.lower(ty, expr)?;
                    writeln!(stmts, "{indent}const list{n} = {lowered};")?;
                    vec![Flat { expr: format!("@intFromPtr(list{n}.ptr)"), ty: "usize" }, Flat { expr: format!("list{n}.len"), ty: "usize" }]
                }
                TypeDefKind::Option(t) => {
                    let t = *t;
                    let n = self.tmp;
                    self.tmp += 1;
                    let mut inner = String::new();
                    let payload = self.flat_lower(&t, &format!("some{n}"), &mut inner, &format!("{indent}    "))?;
                    let mut out = vec![Flat { expr: format!("flat{n}_0"), ty: "u32" }];
                    writeln!(stmts, "{indent}var flat{n}_0: u32 = 0;")?;
                    for (i, p) in payload.iter().enumerate() {
                        writeln!(stmts, "{indent}var flat{n}_{}: {} = 0;", i + 1, p.ty)?;
                        out.push(Flat { expr: format!("flat{n}_{}", i + 1), ty: p.ty });
                    }
                    writeln!(stmts, "{indent}if ({expr}) |some{n}| {{\n{indent}    flat{n}_0 = 1;")?;
                    stmts.push_str(&inner);
                    for (i, p) in payload.iter().enumerate() {
                        writeln!(stmts, "{indent}    flat{n}_{} = {};", i + 1, p.expr)?;
                    }
                    writeln!(stmts, "{indent}}}")?;
                    out
                }
                kind => return Err(unsupported(kind_name(kind))),
            },
        })
    }

    /// The Zig value of core values taken from `values`.
    fn flat_lift(&mut self, ty: &Type, values: &mut impl Iterator<Item = String>) -> Result<String> {
        let mut next = || values.next().ok_or_else(|| anyhow::anyhow!("the core signature has fewer values than the WIT type"));
        Ok(match self.deref(ty)? {
            DType::Prim(Type::Bool) => format!("({} != 0)", next()?),
            DType::Prim(Type::U8) => format!("@as(u8, @intCast({}))", next()?),
            DType::Prim(Type::U16) => format!("@as(u16, @intCast({}))", next()?),
            DType::Prim(Type::S8) => format!("@as(i8, @truncate(@as(i32, @bitCast({}))))", next()?),
            DType::Prim(Type::S16) => format!("@as(i16, @truncate(@as(i32, @bitCast({}))))", next()?),
            DType::Prim(Type::S32) => format!("@as(i32, @bitCast({}))", next()?),
            DType::Prim(Type::S64) => format!("@as(i64, @bitCast({}))", next()?),
            DType::Prim(Type::Char) => format!("@as(u21, @intCast({}))", next()?),
            DType::Prim(Type::String) => {
                let (p, l) = (next()?, next()?);
                format!("@as([*]const u8, @ptrFromInt({p}))[0..{l}]")
            }
            DType::Prim(_) => next()?,
            DType::Id(id) => match &self.resolve.types[id].kind {
                TypeDefKind::Record(r) => {
                    let zig = self.record(id)?.0;
                    let fields = r.fields.clone();
                    let mut parts = Vec::new();
                    for f in &fields {
                        parts.push(format!(".{} = {}", ident(&snake(&f.name)), self.flat_lift(&f.ty, values)?));
                    }
                    format!("@as({zig}, .{{ {} }})", parts.join(", "))
                }
                TypeDefKind::Tuple(t) => {
                    let zig = self.zig(ty)?;
                    let types = t.types.clone();
                    let items = types.iter().map(|t| self.flat_lift(t, values)).collect::<Result<Vec<_>>>()?;
                    format!("@as({zig}, .{{ {} }})", items.join(", "))
                }
                TypeDefKind::List(t) => {
                    let t = *t;
                    let (p, l) = (values.next().unwrap_or_default(), values.next().unwrap_or_default());
                    let raw = format!("List({}){{ .ptr = @ptrFromInt({p}), .len = {l} }}", self.raw(&t)?);
                    self.lift(ty, &format!("({raw})"))?
                }
                TypeDefKind::Option(t) => {
                    let t = *t;
                    let d = next()?;
                    let zig = self.zig(ty)?;
                    let value = self.flat_lift(&t, values)?;
                    format!("@as({zig}, if ({d} != 0) {value} else null)")
                }
                kind => return Err(unsupported(kind_name(kind))),
            },
        })
    }

    /// An import: its `extern` declaration and the typed function.
    fn import_fn(&mut self, w: &WitFn) -> Result<(String, String)> {
        let func = w.func;
        let raw_name = format!("@\"{}\"", w.name);
        let params: Vec<(String, String)> = func.params.iter().map(|p| Ok((param(&p.name), self.zig(&p.ty)?))).collect::<Result<_>>()?;
        let mut stmts = String::new();
        let mut flat = Vec::new();
        if w.sig.indirect_params {
            let mut fields = Vec::new();
            let mut values = Vec::new();
            for (i, p) in func.params.iter().enumerate() {
                fields.push(format!("f{i}: {}", self.raw(&p.ty)?));
                values.push(format!(".f{i} = {}", self.lower(&p.ty, &param(&p.name))?));
            }
            writeln!(stmts, "        const args: extern struct {{ {} }} = .{{ {} }};", fields.join(", "), values.join(", "))?;
            flat.push(Flat { expr: "@intFromPtr(&args)".into(), ty: "usize" });
        } else {
            for p in &func.params {
                flat.extend(self.flat_lower(&p.ty, &param(&p.name), &mut stmts, "        ")?);
            }
        }
        let result = func.result.as_ref();
        let ret_zig = match result {
            Some(t) => self.zig(t)?,
            None => "void".into(),
        };
        let mut call_tail = String::new();
        if w.sig.retptr {
            let t = result.expect("a return area has a result");
            writeln!(stmts, "        var result: {} = undefined;", self.raw(t)?)?;
            flat.push(Flat { expr: "@intFromPtr(&result)".into(), ty: "usize" });
            write!(call_tail, "\n        return {};", self.lift(t, "result")?)?;
        }
        let core_ret = match (w.sig.retptr, w.sig.results.as_slice()) {
            (true, _) | (false, []) => "void",
            (false, [WasmType::I32]) => "u32",
            (false, [WasmType::I64]) => "u64",
            (false, [WasmType::F32]) => "f32",
            (false, [WasmType::F64]) => "f64",
            (false, other) => return Err(unsupported(&format!("the result {other:?} of {}", func.name))),
        };
        let want = w.sig.params.len();
        if flat.len() != want {
            bail!("{}: {} core parameters, the canonical ABI has {want}", func.name, flat.len());
        }
        let decl_params: Vec<String> = flat.iter().enumerate().map(|(i, f)| format!("p{i}: {}", f.ty)).collect();
        let raw = format!("        extern \"{}\" fn {raw_name}({}) {core_ret};\n", w.module, decl_params.join(", "));
        let args: Vec<&str> = flat.iter().map(|f| f.expr.as_str()).collect();
        let call = format!("raw.{raw_name}({})", args.join(", "));
        let mut body = String::new();
        body.push_str(&doc(&func.docs, "    "));
        let sig: Vec<String> = params.iter().map(|(n, t)| format!("{n}: {t}")).collect();
        writeln!(body, "    pub fn {}({}) {ret_zig} {{", ident(&camel(&func.name)), sig.join(", "))?;
        body.push_str(&stmts);
        match (w.sig.retptr, result) {
            (true, _) => writeln!(body, "        {call};{call_tail}")?,
            (false, None) => writeln!(body, "        {call};")?,
            (false, Some(t)) => {
                let value = self.flat_lift(t, &mut std::iter::once(call.clone()))?;
                writeln!(body, "        return {value};")?;
            }
        }
        body.push_str("    }\n");
        Ok((raw, body))
    }

    /// An export: a function in `S` that `exports` exports, calling the
    /// app's `App.<interface>.<function>`.
    fn export_fn(&mut self, w: &WitFn, ns: &str, local: &str) -> Result<String> {
        let func = w.func;
        let target = format!("App.{ns}.{}", ident(&camel(&func.name)));
        let mut body = String::new();
        let mut params = Vec::new();
        let mut values = Vec::new();
        if w.sig.indirect_params {
            params.push("args_ptr: usize".to_string());
            let mut fields = Vec::new();
            for (i, p) in func.params.iter().enumerate() {
                fields.push(format!("f{i}: {}", self.raw(&p.ty)?));
            }
            writeln!(body, "            const args: *const extern struct {{ {} }} = @ptrFromInt(args_ptr);", fields.join(", "))?;
            for (i, p) in func.params.iter().enumerate() {
                values.push(self.lift(&p.ty, &format!("args.f{i}"))?);
            }
        } else {
            let mut names = Vec::new();
            for (i, t) in w.sig.params.iter().enumerate() {
                let ty = match t {
                    WasmType::I32 => "u32",
                    WasmType::Pointer | WasmType::Length => "usize",
                    WasmType::I64 => "u64",
                    WasmType::F32 => "f32",
                    WasmType::F64 => "f64",
                    other => return Err(unsupported(&format!("a {other:?} parameter in {}", func.name))),
                };
                params.push(format!("p{i}: {ty}"));
                names.push(format!("p{i}"));
            }
            let mut it = names.into_iter();
            for p in &func.params {
                values.push(self.flat_lift(&p.ty, &mut it)?);
            }
        }
        let call = format!("{target}({})", values.join(", "));
        let ret = match (&func.result, w.sig.retptr) {
            (None, _) => {
                writeln!(body, "            {call};")?;
                "void"
            }
            (Some(_), true) => return Err(unsupported(&format!("the result of the export {}", func.name))),
            (Some(t), false) => {
                let mut stmts = String::new();
                let flat = self.flat_lower(t, "result", &mut stmts, "            ")?;
                let [one] = flat.as_slice() else { return Err(unsupported(&format!("the result of the export {}", func.name))) };
                writeln!(body, "            const result = {call};\n{stmts}            return {};", one.expr)?;
                one.ty
            }
        };
        Ok(format!("        fn {local}({}) callconv(.c) {ret} {{\n{body}        }}\n", params.join(", ")))
    }
}

/// A type with aliases followed.
enum DType {
    Prim(Type),
    Id(TypeId),
}

fn prim(t: Type, raw: bool) -> Result<&'static str> {
    Ok(match t {
        Type::Bool if raw => "u8",
        Type::Bool => "bool",
        Type::U8 => "u8",
        Type::U16 => "u16",
        Type::U32 => "u32",
        Type::U64 => "u64",
        Type::S8 => "i8",
        Type::S16 => "i16",
        Type::S32 => "i32",
        Type::S64 => "i64",
        Type::F32 => "f32",
        Type::F64 => "f64",
        Type::Char if raw => "u32",
        Type::Char => "u21",
        Type::String if raw => "Str",
        Type::String => "[]const u8",
        other => return Err(unsupported(&format!("{other:?}"))),
    })
}

fn kind_name(kind: &TypeDefKind) -> &'static str {
    match kind {
        TypeDefKind::Resource | TypeDefKind::Handle(_) => "a resource",
        TypeDefKind::Flags(_) => "flags",
        TypeDefKind::Variant(_) => "a variant",
        TypeDefKind::Enum(_) => "an enum",
        TypeDefKind::Result(_) => "a result",
        TypeDefKind::Map(..) => "a map",
        TypeDefKind::FixedLengthList(..) => "a fixed-length list",
        TypeDefKind::Future(_) | TypeDefKind::Stream(_) => "async",
        _ => "this type",
    }
}

/// WIT docs as Zig doc comments.
fn doc(docs: &Docs, indent: &str) -> String {
    let Some(text) = docs.contents.as_deref().map(str::trim).filter(|t| !t.is_empty()) else { return String::new() };
    text.lines().map(|l| format!("{indent}/// {l}\n").replace("/// \n", "///\n")).collect()
}

/// `set-html` -> `setHtml`.
fn camel(name: &str) -> String {
    let p = pascal(name);
    let mut c = p.chars();
    c.next().map(|f| f.to_ascii_lowercase().to_string() + c.as_str()).unwrap_or_default()
}

/// `request` -> `Request`, `wall-clock` -> `WallClock`.
fn pascal(name: &str) -> String {
    name.split('-')
        .map(|w| {
            let mut c = w.chars();
            c.next().map(|f| f.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default()
        })
        .collect()
}

/// `wall-clock` -> `wall_clock`.
fn snake(name: &str) -> String {
    name.replace('-', "_")
}

/// A parameter: its WIT name with a trailing underscore, so it never
/// shadows a declaration of the bindings (Zig doesn't allow that):
/// `handler` is `handler_`.
fn param(name: &str) -> String {
    format!("{}_", snake(name))
}

/// A Zig identifier: keywords and primitive type names are quoted,
/// `@"type"`.
fn ident(name: &str) -> String {
    const RESERVED: &[&str] = &[
        "addrspace",
        "align",
        "allowzero",
        "and",
        "anyframe",
        "anytype",
        "asm",
        "break",
        "callconv",
        "catch",
        "comptime",
        "const",
        "continue",
        "defer",
        "else",
        "enum",
        "errdefer",
        "error",
        "export",
        "extern",
        "fn",
        "for",
        "if",
        "inline",
        "linksection",
        "noalias",
        "noinline",
        "nosuspend",
        "opaque",
        "or",
        "orelse",
        "packed",
        "pub",
        "resume",
        "return",
        "struct",
        "suspend",
        "switch",
        "test",
        "threadlocal",
        "try",
        "union",
        "unreachable",
        "var",
        "volatile",
        "while",
        "bool",
        "type",
        "void",
        "anyerror",
        "anyopaque",
        "noreturn",
        "isize",
        "usize",
        "true",
        "false",
        "null",
        "undefined",
        "u8",
        "u16",
        "u32",
        "u64",
        "i8",
        "i16",
        "i32",
        "i64",
        "f16",
        "f32",
        "f64",
        "f80",
        "f128",
    ];
    if RESERVED.contains(&name) { format!("@\"{name}\"") } else { name.to_string() }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn load(wit: &str) -> (Resolve, WorldId) {
        let mut resolve = Resolve::new();
        let pkg = resolve.push_str("test.wit", wit).unwrap();
        let world = resolve.select_world(&[pkg], None).unwrap();
        (resolve, world)
    }

    fn appos() -> String {
        let mut resolve = Resolve::new();
        let pkg = resolve.push_str("appos.wit", include_str!("../../../wit/appos.wit")).unwrap();
        let world = resolve.select_world(&[pkg], None).unwrap();
        generate(&resolve, world).unwrap()
    }

    #[test]
    fn imports_are_extern_functions_of_their_wit_module() {
        let code = appos();
        assert!(code.contains("extern \"appos:framework/page@0.1.0\" fn @\"set-html\"(p0: usize, p1: usize, p2: usize, p3: usize) void;"), "{code}");
        assert!(code.contains(
            "    pub fn setHtml(name_: []const u8, html_: []const u8) void {\n        raw.@\"set-html\"(@intFromPtr(name_.ptr), name_.len, @intFromPtr(html_.ptr), html_.len);\n    }"
        ));
        assert!(code.contains("    pub fn setStatus(code_: u16) void {\n        raw.@\"set-status\"(@as(u32, code_));\n    }"), "{code}");
    }

    #[test]
    fn results_come_back_through_a_return_area() {
        let code = appos();
        assert!(code.contains("    pub fn get(key_: []const u8) ?[]const u8 {\n        var result: Option(Str) = undefined;"), "{code}");
        assert!(
            code.contains("pub fn scan(prefix_: []const u8, after_: ?[]const u8, limit_: u32, reverse_: bool) []const @Tuple(&.{ []const u8, []const u8 })")
        );
        assert!(code.contains("        if (after_) |some0| {\n            flat0_0 = 1;\n"), "{code}");
    }

    #[test]
    fn exports_call_the_app_with_zig_values() {
        let code = appos();
        assert!(code.contains("pub const Request = struct {"), "{code}");
        assert!(code.contains("        params: []const @Tuple(&.{ []const u8, []const u8 }),"));
        assert!(code.contains(
            "        fn handler_start(args_ptr: usize) callconv(.c) void {\n            const args: *const extern struct { f0: Str, f1: types.RawRequest } = @ptrFromInt(args_ptr);\n            App.handler.start(args.f0.ptr[0..args.f0.len], types.liftRequest(args.f1));\n"
        ), "{code}");
        assert!(code.contains("    @export(&S.handler_start, .{ .name = \"appos:framework/handler@0.1.0#start\" });"));
        assert!(code.contains("    @export(&cabiRealloc, .{ .name = \"cabi_realloc\" });"));
    }

    #[test]
    fn scalar_results_and_flat_parameters() {
        let (resolve, world) = load(
            "package t:t;\ninterface leads { count-leads: func(since: s64, ok: bool) -> u32; }\ninterface api { score: func(name: string, weight: f64) -> bool; }\nworld w { import leads; export api; }",
        );
        let code = generate(&resolve, world).unwrap();
        assert!(code.contains("    pub fn countLeads(since_: i64, ok_: bool) u32 {\n        return raw.@\"count-leads\"(@as(u64, @bitCast(since_)), @as(u32, @intFromBool(ok_)));"), "{code}");
        assert!(code.contains(
            "        fn api_score(p0: usize, p1: usize, p2: f64) callconv(.c) u32 {\n            const result = App.api.score(@as([*]const u8, @ptrFromInt(p0))[0..p1], p2);\n            return @as(u32, @intFromBool(result));"
        ), "{code}");
    }

    #[test]
    fn unsupported_types_are_named() {
        let (resolve, world) = load("package t:t;\ninterface i { f: func() -> result<u32, string>; }\nworld w { import i; }");
        assert_eq!(generate(&resolve, world).unwrap_err().to_string(), "a result in the WIT isn't supported for Zig apps yet");
    }
}
